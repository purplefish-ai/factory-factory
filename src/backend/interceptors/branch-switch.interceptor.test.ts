import { beforeEach, describe, expect, it, vi } from 'vitest';
import type { InterceptorContext, ToolEvent } from './types';

const mocks = vi.hoisted(() => ({
  gitCommand: vi.fn(),
  invalidate: vi.fn(),
  setBranchNameAndClearAutoGenerated: vi.fn(),
}));
vi.mock('@/backend/lib/shell', () => ({ gitCommand: mocks.gitCommand }));
vi.mock('@/backend/services/workspace', () => ({ workspaceDataService: mocks }));
vi.mock('@/backend/services/workspace-git-state.service', () => ({
  workspaceGitStateService: { invalidate: mocks.invalidate },
}));

import { createBranchNamingInterceptor } from './branch-naming.interceptor';

const context: InterceptorContext = {
  sessionId: 'session',
  workspaceId: 'workspace',
  workingDir: '/tmp/workspace',
  timestamp: new Date(),
};

async function complete(command: string, isError = false, completionOnly = false) {
  const interceptor = createBranchNamingInterceptor();
  const event: ToolEvent = {
    toolUseId: 'switch',
    toolName: 'exec_command',
    input: { cmd: command },
  };
  if (!completionOnly) {
    await interceptor.onToolStart!(event, context);
  }
  await interceptor.onToolComplete!({ ...event, output: { content: '', isError } }, context);
}

describe('workspace branch switches', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mocks.gitCommand.mockResolvedValue({
      code: 0,
      stdout: 'purplefish-ai/steel-model-view\n',
      stderr: '',
    });
    mocks.setBranchNameAndClearAutoGenerated.mockResolvedValue({});
  });

  it.each([
    'git switch -c purplefish-ai/steel-model-view origin/main',
    'git switch existing-branch',
    'git checkout -b new-branch origin/main',
    'git checkout -B new-branch origin/main',
    "sh -c 'git switch existing-branch'",
  ])('persists the actual branch after %s so discovery can find its PR', async (command) => {
    await complete(command);
    expect(mocks.setBranchNameAndClearAutoGenerated).toHaveBeenCalledWith(
      'workspace',
      'purplefish-ai/steel-model-view'
    );
    expect(mocks.invalidate).toHaveBeenCalledWith('/tmp/workspace');
  });

  it('handles a switch supplied only at completion', async () => {
    await complete('git switch existing-branch', false, true);
    expect(mocks.setBranchNameAndClearAutoGenerated).toHaveBeenCalledOnce();
  });

  it.each([
    'echo "git switch new-branch"',
    'rg "git switch" README.md',
    '# git switch new-branch',
    'git checkout -- file.ts',
  ])('does not treat text or file checkout as a branch switch: %s', async (command) => {
    await complete(command);
    expect(mocks.gitCommand).not.toHaveBeenCalled();
    expect(mocks.setBranchNameAndClearAutoGenerated).not.toHaveBeenCalled();
  });

  it('does not persist a failed switch', async () => {
    await complete('git switch missing', true);
    expect(mocks.setBranchNameAndClearAutoGenerated).not.toHaveBeenCalled();
  });

  it('does not save detached HEAD as a branch', async () => {
    mocks.gitCommand.mockResolvedValue({ code: 0, stdout: 'HEAD\n', stderr: '' });
    await complete('git switch --detach origin/main');
    expect(mocks.setBranchNameAndClearAutoGenerated).not.toHaveBeenCalled();
  });
});
