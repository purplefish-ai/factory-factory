import { beforeEach, expect, it, vi } from 'vitest';
import { createLogger } from '@/backend/services/logger.service';
import { AutoGeneratedBranchRenamer } from './auto-branch-rename';
import type { InterceptorContext } from './types';

const mocks = vi.hoisted(() => ({
  git: vi.fn(),
  workspace: vi.fn(),
  project: vi.fn(),
  accept: vi.fn(),
}));
vi.mock('@/backend/lib/shell', () => ({ gitCommand: mocks.git }));
vi.mock('@/backend/services/workspace', () => ({
  workspaceDataService: {
    findById: mocks.workspace,
    setBranchNameAndClearAutoGenerated: mocks.accept,
  },
  projectManagementService: { findById: mocks.project },
}));
vi.mock('@/backend/services/workspace-git-state.service', () => ({
  workspaceGitStateService: { invalidate: vi.fn() },
}));
const context: InterceptorContext = {
  sessionId: 's',
  workspaceId: 'workspace-1',
  workingDir: '/tmp/workspace',
  timestamp: new Date(),
};
const labels = { detected: 'push', before: 'push', interceptor: 'test' };
beforeEach(() => {
  vi.resetAllMocks();
  mocks.workspace.mockResolvedValue({
    id: 'workspace-1',
    projectId: 'p',
    name: 'Initial prompt',
    branchName: 'owner/automatic',
    isAutoGeneratedBranch: true,
    conversationSummary: { branch: 'workspace-discoverability' },
  });
  mocks.project.mockResolvedValue({ githubOwner: 'owner' });
});
it('uses the saved model suggestion and project prefix before publication', async () => {
  mocks.git.mockImplementation((args: string[]) =>
    Promise.resolve({ code: args[0] === 'show-ref' ? 1 : 0, stdout: '', stderr: '' })
  );
  const result = await new AutoGeneratedBranchRenamer().renameIfAutoGenerated(
    context,
    labels,
    createLogger('test')
  );
  expect(result?.newBranchName).toBe('owner/workspace-discoverability');
  expect(mocks.accept).toHaveBeenCalledWith('workspace-1', 'owner/workspace-discoverability');
});
it('adds a workspace suffix on collision', async () => {
  mocks.git.mockImplementation((args: string[]) =>
    Promise.resolve({
      code:
        args.at(-1) === 'refs/heads/owner/workspace-discoverability'
          ? 0
          : args[0] === 'show-ref'
            ? 1
            : 0,
      stdout: '',
      stderr: '',
    })
  );
  const result = await new AutoGeneratedBranchRenamer().renameIfAutoGenerated(
    context,
    labels,
    createLogger('test')
  );
  expect(result?.newBranchName).toBe('owner/workspace-discoverability-rkspace1');
});
