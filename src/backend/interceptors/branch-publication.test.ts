import { beforeEach, expect, it, vi } from 'vitest';
import { subscribeWorkspaceBranchPublication } from '@/backend/orchestration/workspace-branch-publication.orchestrator';
import {
  workspaceDataService,
  projectManagementService,
  WorkspaceSnapshotStore,
} from '@/backend/services/workspace';
import { unsafeCoerce } from '@/test-utils/unsafe-coerce';
import { createBranchNamingInterceptor } from './branch-naming.interceptor';
import type { InterceptorContext, ToolEvent } from './types';

const mocks = vi.hoisted(() => ({
  persist: vi.fn(),
  find: vi.fn(),
  git: vi.fn(),
  invalidate: vi.fn(),
}));
vi.mock('@/backend/services/workspace/resources/workspace.accessor', () => ({
  workspaceAccessor: {
    setBranchNameAndClearDiscoverySchedule: mocks.persist,
    findById: mocks.find,
  },
}));
vi.mock('@/backend/lib/shell', () => ({ gitCommand: mocks.git }));
vi.mock('@/backend/services/workspace-git-state.service', () => ({
  workspaceGitStateService: { invalidate: mocks.invalidate },
}));

const context: InterceptorContext = {
  sessionId: 'session',
  workspaceId: 'workspace',
  workingDir: '/worktree',
  timestamp: new Date(100),
};
function event(command: string, isError = false): ToolEvent {
  return {
    toolUseId: 'tool',
    toolName: 'Bash',
    input: { command },
    output: { isError, content: '' },
  };
}
function fixture() {
  const store = new WorkspaceSnapshotStore();
  store.configure({
    deriveFlowState: () => ({
      phase: 'NO_PR',
      ciObservation: 'NOT_FETCHED',
      hasActivePr: false,
      isWorking: false,
      shouldAnimateRatchetButton: false,
    }),
    deriveSidebarStatus: () => ({ activityState: 'IDLE', ciState: 'NONE' }),
  });
  store.upsert(
    'workspace',
    { projectId: 'project', status: 'READY', branchName: 'old' },
    'seed',
    100
  );
  const unsubscribe = subscribeWorkspaceBranchPublication(workspaceDataService, store);
  return {
    store,
    close: () => {
      unsubscribe();
      store.clear();
    },
  };
}
beforeEach(() => {
  vi.restoreAllMocks();
  vi.clearAllMocks();
  mocks.find.mockResolvedValue({
    id: 'workspace',
    projectId: 'project',
    name: 'Meaningful task',
    branchName: 'old',
    isAutoGeneratedBranch: true,
  });
  vi.spyOn(projectManagementService, 'findById').mockResolvedValue(
    unsafeCoerce({ githubOwner: 'owner' })
  );
  mocks.persist.mockResolvedValue({
    id: 'workspace',
    branchName: 'canonical DB branch',
    status: 'READY',
    updatedAt: new Date(200),
  });
  mocks.git.mockResolvedValue({ code: 0, stdout: 'canonical HEAD\n', stderr: '' });
});

it('manual successful tool completion publishes the DB-accepted branch after resolving canonical HEAD', async () => {
  const { store, close } = fixture();
  const interceptor = createBranchNamingInterceptor();
  try {
    const rename = event('git branch -m requested');
    await interceptor.onToolStart!(rename, context);
    expect(store.getByWorkspaceId('workspace')?.branchName).toBe('old');
    await interceptor.onToolComplete!(rename, context);
    expect(mocks.git).toHaveBeenCalledWith(['rev-parse', '--abbrev-ref', 'HEAD'], '/worktree');
    expect(mocks.persist).toHaveBeenCalledExactlyOnceWith('workspace', 'canonical HEAD');
    expect(store.getByWorkspaceId('workspace')?.branchName).toBe('canonical DB branch');
  } finally {
    close();
  }
});
it.each(['git push origin HEAD', 'gh pr create --title Task'])(
  'automatic %s publishes through the same accepted gateway before the external tool runs',
  async (command) => {
    const { store, close } = fixture();
    const interceptor = createBranchNamingInterceptor();
    try {
      await interceptor.onToolStart!(event(command), context);
      expect(mocks.git).toHaveBeenCalledWith(
        ['branch', '-m', 'owner/meaningful-task'],
        '/worktree'
      );
      expect(mocks.persist).toHaveBeenCalledExactlyOnceWith('workspace', 'owner/meaningful-task');
      expect(store.getByWorkspaceId('workspace')?.branchName).toBe('canonical DB branch');
    } finally {
      close();
    }
  }
);
it.each(['git', 'database'] as const)(
  'automatic %s failure publishes nothing and releases the claim for retry',
  async (failure) => {
    const { store, close } = fixture();
    const interceptor = createBranchNamingInterceptor();
    try {
      if (failure === 'git') {
        mocks.git
          .mockResolvedValueOnce({ code: 1, stdout: '', stderr: 'failed' })
          .mockResolvedValueOnce({ code: 1, stdout: '', stderr: 'fallback failed' });
      } else {
        mocks.persist.mockRejectedValueOnce(new Error('rollback'));
      }
      await interceptor.onToolStart!(event('git push origin HEAD'), context);
      expect(store.getByWorkspaceId('workspace')?.branchName).toBe('old');
      await interceptor.onToolStart!(event('git push origin HEAD'), context);
      expect(store.getByWorkspaceId('workspace')?.branchName).toBe('canonical DB branch');
    } finally {
      close();
    }
  }
);
it.each(['tool', 'git', 'empty HEAD', 'database'] as const)(
  'manual %s failure publishes nothing',
  async (failure) => {
    const { store, close } = fixture();
    const interceptor = createBranchNamingInterceptor();
    try {
      if (failure === 'git') {
        mocks.git.mockResolvedValueOnce({ code: 1, stdout: '', stderr: 'failed' });
      }
      if (failure === 'empty HEAD') {
        mocks.git.mockResolvedValueOnce({ code: 0, stdout: '\n', stderr: '' });
      }
      if (failure === 'database') {
        mocks.persist.mockRejectedValueOnce(new Error('rollback'));
      }
      const rename = event('git branch -m requested', failure === 'tool');
      await interceptor.onToolStart!(rename, context);
      await interceptor.onToolComplete!(rename, context);
      expect(store.getByWorkspaceId('workspace')?.branchName).toBe('old');
      if (failure !== 'database') {
        expect(mocks.persist).not.toHaveBeenCalled();
      }
    } finally {
      close();
    }
  }
);
