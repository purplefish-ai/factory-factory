import { randomUUID } from 'node:crypto';
import { z } from 'zod';
import {
  buildWorkspaceMetadataInput,
  metadataMessageId,
} from '@/backend/prompts/workspace-metadata';
import { SERVICE_INTERVAL_MS, SERVICE_LIMITS } from '@/backend/services/constants';
import { type JobRunner, jobRunner } from '@/backend/services/job-runner.service';
import { createLogger } from '@/backend/services/logger.service';
import type { generateWorkspaceMetadata } from '@/backend/services/session';
import type { workspaceDataService } from '@/backend/services/workspace';
import type { HistoryMessage } from '@/shared/acp-protocol';
import {
  WorkspaceMetadataResultSchema,
  type WorkspaceMetadataResult,
  type WorkspaceConversationSummary,
} from '@/shared/workspace-conversation-summary';

const JOB = 'workspace-metadata';
const COOLDOWN_MS = 120_000;
const logger = createLogger(JOB);
type MetadataWorkspace = {
  id: string;
  projectId: string;
  name: string;
  status: string;
  creationSource: string;
  creationMetadata?: unknown;
  conversationSummary?: WorkspaceConversationSummary | null;
};
const nameProvenanceSchema = z.object({ autoGeneratedName: z.string() });
interface Dependencies {
  findSession(id: string): Promise<{
    id: string;
    workspaceId: string;
    provider: 'CLAUDE' | 'CODEX';
    codexAccountId: string | null;
  } | null>;
  history(sessionId: string): HistoryMessage[];
  findWorkspace(id: string): Promise<MetadataWorkspace | null>;
  reserve: typeof workspaceDataService.reserveMetadata;
  accept: typeof workspaceDataService.acceptMetadata;
  generate: typeof generateWorkspaceMetadata;
  publish(
    workspace: { id: string; name: string; updatedAt: Date },
    projectId: string,
    summary: WorkspaceConversationSummary
  ): void;
  now?: () => number;
}
type Pending = {
  sequence: number;
  sessionId: string;
  provider: 'CLAUDE' | 'CODEX';
  codexAccountId: string | null;
  history: HistoryMessage[];
  dueAt: number;
  failures: number;
  initialOnly: boolean;
};

/** One bounded, best-effort queue across all conversations in an application. */
export class WorkspaceMetadataOrchestrator {
  private readonly pending = new Map<string, Pending>();
  private readonly attemptedAt = new Map<string, number>();
  private readonly latestSchedules = new Map<string, { sequence: number; at: number }>();
  private readonly initialSessions = new Map<
    string,
    { workspaceId: string | null; invalidated: boolean }
  >();
  private sequence = 0;
  private readonly now: () => number;
  private stopped = false;

  constructor(
    private readonly dependencies: Dependencies,
    private readonly runner: JobRunner = jobRunner
  ) {
    this.now = dependencies.now ?? Date.now;
    runner.register({
      name: JOB,
      intervalMs: SERVICE_INTERVAL_MS.workspaceMetadata,
      run: (signal) => this.run(signal),
    });
  }

  start() {
    this.stopped = false;
    this.runner.start(JOB);
  }
  async stop() {
    this.stopped = true;
    this.pending.clear();
    await this.runner.stop(JOB);
    this.attemptedAt.clear();
    this.latestSchedules.clear();
    this.initialSessions.clear();
  }

  private skipInitial(sessionId: string, initialOnly: boolean): boolean {
    const session = initialOnly ? this.initialSessions.get(sessionId) : undefined;
    if (!session) {
      return false;
    }
    // Also invalidate an initial schedule whose session lookup has not returned yet.
    session.invalidated = true;
    const entry = session.workspaceId ? this.pending.get(session.workspaceId) : undefined;
    if (session.workspaceId && entry?.initialOnly && entry.sessionId === sessionId) {
      this.discard(session.workspaceId, entry);
    }
    return true;
  }

  private rememberSession(sessionId: string, workspaceId: string | null) {
    const invalidated = this.initialSessions.get(sessionId)?.invalidated ?? false;
    this.initialSessions.set(sessionId, { workspaceId, invalidated });
    if (this.initialSessions.size > SERVICE_LIMITS.workspaceScopedCacheMaxEntries) {
      const oldest = this.initialSessions.keys().next().value;
      if (oldest) {
        this.initialSessions.delete(oldest);
      }
    }
  }

  private skipInitialSnapshot(sessionId: string, workspaceId: string, initialOnly: boolean) {
    return (
      initialOnly &&
      (this.initialSessions.get(sessionId)?.invalidated ||
        this.pending.get(workspaceId)?.initialOnly === false)
    );
  }

  private queueFull(workspaceId: string) {
    return (
      !this.pending.has(workspaceId) &&
      this.pending.size >= SERVICE_LIMITS.workspaceScopedCacheMaxEntries
    );
  }

  async schedule(sessionId: string, initialOnly = false): Promise<void> {
    const sequence = ++this.sequence;
    if (this.skipInitial(sessionId, initialOnly)) {
      return;
    }
    if (initialOnly) {
      this.rememberSession(sessionId, null);
    }
    try {
      const snapshot = initialOnly ? undefined : this.dependencies.history(sessionId);
      const session = await this.dependencies.findSession(sessionId);
      if (this.stopped || !session) {
        return;
      }
      if ((this.latestSchedules.get(session.workspaceId)?.sequence ?? 0) > sequence) {
        return;
      }
      this.rememberSession(sessionId, session.workspaceId);
      if (this.skipInitialSnapshot(sessionId, session.workspaceId, initialOnly)) {
        return;
      }
      const history = snapshot ?? this.dependencies.history(sessionId);
      if (!history.some((m) => m.type === 'user')) {
        return;
      }
      if (this.queueFull(session.workspaceId)) {
        return;
      }
      // Capture text now; later events replace this entry and invalidate in-flight inference.
      this.latestSchedules.set(session.workspaceId, { sequence, at: this.now() });
      this.pending.set(session.workspaceId, {
        sequence,
        sessionId,
        provider: session.provider,
        codexAccountId: session.codexAccountId,
        history,
        failures: 0,
        initialOnly,
        dueAt: Math.max(
          this.now(),
          (this.attemptedAt.get(session.workspaceId) ?? -COOLDOWN_MS) + COOLDOWN_MS
        ),
      });
    } catch {
      logger.debug('Could not queue workspace metadata', { sessionId });
    } finally {
      if (this.initialSessions.get(sessionId)?.workspaceId === null) {
        this.initialSessions.delete(sessionId);
      }
    }
  }

  async run(signal: AbortSignal): Promise<void> {
    for (const [id, schedule] of this.latestSchedules) {
      if (this.now() - schedule.at > 10 * 60_000 && !this.pending.has(id)) {
        this.latestSchedules.delete(id);
      }
    }
    for (const [id, time] of this.attemptedAt) {
      if (this.now() - time > 10 * 60_000) {
        this.attemptedAt.delete(id);
      }
    }
    for (const [workspaceId, entry] of this.pending) {
      if (signal.aborted || this.stopped) {
        return;
      }
      if (entry.dueAt > this.now()) {
        continue;
      }
      try {
        await this.processEntry(workspaceId, entry, signal);
      } catch {
        entry.failures++;
        entry.dueAt = this.now() + Math.min(10 * 60_000, COOLDOWN_MS * 2 ** (entry.failures - 1));
        // Never log private provider diagnostics or conversation content.
        logger.debug('Workspace metadata deferred', { workspaceId });
      }
    }
  }

  private discard(workspaceId: string, entry: Pending) {
    if (this.pending.get(workspaceId) === entry) {
      this.pending.delete(workspaceId);
    }
  }

  private async processEntry(workspaceId: string, entry: Pending, signal: AbortSignal) {
    entry.dueAt = Math.max(
      entry.dueAt,
      (this.attemptedAt.get(workspaceId) ?? -COOLDOWN_MS) + COOLDOWN_MS
    );
    if (entry.dueAt > this.now()) {
      return;
    }
    const workspace = await this.dependencies.findWorkspace(workspaceId);
    if (!workspace || ['ARCHIVING', 'ARCHIVED'].includes(workspace.status)) {
      this.discard(workspaceId, entry);
      return;
    }
    const previous = workspace.conversationSummary ?? null;
    if (entry.initialOnly && previous) {
      this.discard(workspaceId, entry);
      return;
    }
    const persistedCooldown = previous ? Date.parse(previous.generatedAt) + COOLDOWN_MS : 0;
    if (persistedCooldown > this.now()) {
      entry.dueAt = persistedCooldown;
      return;
    }
    const input = buildWorkspaceMetadataInput(entry.history, previous);
    const alreadySummarized =
      previous?.sourceSessionId === entry.sessionId &&
      previous.sourceMessageId === input.sourceMessageId;
    if (!input.sourceMessageId || alreadySummarized) {
      this.discard(workspaceId, entry);
      return;
    }
    const requestId = randomUUID();
    if (!(await this.dependencies.reserve(workspaceId, requestId))) {
      this.discard(workspaceId, entry);
      return;
    }
    if (this.pending.get(workspaceId) !== entry || signal.aborted) {
      return;
    }
    this.attemptedAt.set(workspaceId, this.now());
    await this.generateEntry(workspace, entry, input, requestId, signal);
  }

  private async generateEntry(
    workspace: MetadataWorkspace,
    entry: Pending,
    input: ReturnType<typeof buildWorkspaceMetadataInput>,
    requestId: string,
    signal: AbortSignal
  ) {
    const workspaceId = workspace.id;
    const result = WorkspaceMetadataResultSchema.parse(
      await this.dependencies.generate(
        {
          provider: entry.provider,
          codexAccountId: entry.codexAccountId,
          input: { ...input, currentName: workspace.name },
        },
        signal
      )
    );
    if (signal.aborted || this.stopped || this.pending.get(workspaceId) !== entry) {
      return;
    }
    if (!this.hasCapturedSource(entry.sessionId, input.sourceMessageId)) {
      // Rewritten history invalidates the snapshot; appended unfinished turns do not.
      this.discard(workspaceId, entry);
      return;
    }
    await this.acceptResult(workspace, entry, requestId, result, input.sourceMessageId, signal);
    this.discard(workspaceId, entry);
  }

  private hasCapturedSource(sessionId: string, sourceMessageId: string): boolean {
    const history = this.dependencies.history(sessionId);
    if (history.length === 0) {
      return true;
    }
    for (let index = history.length - 1; index >= 0; index--) {
      const message = history[index];
      if (message && metadataMessageId(message) === sourceMessageId) {
        return true;
      }
    }
    return false;
  }

  private async acceptResult(
    workspace: MetadataWorkspace,
    entry: Pending,
    requestId: string,
    result: WorkspaceMetadataResult,
    sourceMessageId: string,
    signal: AbortSignal
  ) {
    const previous = workspace.conversationSummary;
    const provenance = nameProvenanceSchema.safeParse(workspace.creationMetadata);
    const rename =
      !previous &&
      workspace.creationSource === 'MANUAL' &&
      provenance.success &&
      provenance.data.autoGeneratedName === workspace.name;
    const generatedAt = new Date(this.now());
    const isCurrent = () =>
      !(signal.aborted || this.stopped) && this.pending.get(workspace.id) === entry;
    if (!isCurrent()) {
      return;
    }
    const accepted = await this.dependencies.accept({
      workspaceId: workspace.id,
      requestId,
      expectedName: workspace.name,
      rename,
      result,
      sourceSessionId: entry.sessionId,
      sourceMessageId,
      generatedAt,
      isCurrent,
    });
    if (accepted && isCurrent()) {
      this.dependencies.publish(accepted, workspace.projectId, {
        ...result,
        title: previous?.title ?? result.title,
        branch: previous?.branch ?? result.branch,
        sourceSessionId: entry.sessionId,
        sourceMessageId,
        generatedAt: generatedAt.toISOString(),
      });
    }
  }
}
