/** Strip optional/nullable/default/array wrappers down to the record schema. */
function unwrap(schema: z.core.$ZodType): z.core.$ZodType {
  if (
    schema instanceof z.ZodOptional ||
    schema instanceof z.ZodNullable ||
    schema instanceof z.ZodDefault
  ) {
    return unwrap(schema.unwrap());
  }
  if (schema instanceof z.ZodArray) {
    return unwrap(schema.element);
  }
  return schema;
}

function recordAt(root: z.core.$ZodType, path: readonly string[]): z.ZodObject {
  let schema = unwrap(root);
  for (const key of path) {
    if (!(schema instanceof z.ZodObject && key in schema.shape)) {
      throw new Error(`Export schema has no object field at ${path.join('.')} (missing ${key})`);
    }
    schema = unwrap(schema.shape[key]);
  }
  if (!(schema instanceof z.ZodObject)) {
    throw new Error(`Export schema at ${path.join('.')} is not an object`);
  }
  return schema;
}

const manifest = createBaseRecoveryManifest();

/** The variant of the export union that validates what exportData writes today. */
function currentExportSchema(): z.ZodObject {
  const matches = exportDataSchema.options.filter(
    (option): option is Extract<typeof option, z.ZodObject> =>
      option instanceof z.ZodObject &&
      recordAt(option, ['meta', 'recovery']).shape.profile?.safeParse(manifest.profile).success ===
        true
  );
  expect(matches).toHaveLength(1);
  return matches[0] as z.ZodObject;
}

describe('backup export column coverage', () => {
  it('maps exactly the models the recovery manifest says the export covers', () => {
    const covered = manifest.coverage
      .filter((entry) => entry.status !== 'EXCLUDED')
      .map((entry) => entry.model)
      .sort();

    expect(Object.keys(exportColumns).sort()).toEqual(covered);
  });

  it.each(Object.entries(exportColumns))('%s: every column is exported or excluded', (_, entry) => {
    expect(Object.keys(entry.columns).sort()).toEqual(Object.values(entry.scalarFields).sort());
  });

  it.each(Object.entries(exportColumns))(
    '%s: exported columns exist in the current export format',
    (_, entry) => {
      const record = recordAt(currentExportSchema(), entry.path);
      const missing = Object.entries(entry.columns).flatMap(([column, mapping]) => {
        if (!('exportedAs' in mapping)) {
          return [];
        }
        const key = mapping.exportedAs ?? column;
        return key in record.shape ? [] : [`${column} -> ${key}`];
      });

      expect(missing).toEqual([]);
    }
  );

  it.each(Object.entries(exportColumns))('%s: exclusions give a reason', (_, entry) => {
    for (const mapping of Object.values(entry.columns)) {
      if ('excluded' in mapping) {
        expect(mapping.excluded.trim().length).toBeGreaterThan(10);
      }
    }
  });

  it('keeps the known run-script gap visible', () => {
    expect(exportColumns.WorkspaceRunScript?.columns.postRunCommand).toEqual({
      excluded: expect.stringMatching(/^Gap:/),
    });
  });
});
