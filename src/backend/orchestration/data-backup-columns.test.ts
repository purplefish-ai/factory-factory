/**
 * Column-level drift guard for the JSON backup.
 *
 * Every Prisma scalar column of every model the export covers must be either
 * carried by the current export format or listed here as deliberately excluded
 * with a reason. A new column therefore fails this test until someone decides
 * whether backups should carry it. Reasons starting with "Gap:" record columns
 * the export does not carry today but arguably should.
 */
import { Prisma } from '@prisma-gen/client';
import { createBaseRecoveryManifest } from './data-backup-manifest';

type Column = { exportedAs: string | undefined } | { excluded: string };

/** Carried under the same name, or under `key` when the export renames or flattens it. */
const exported = (key?: string): Column => ({ exportedAs: key });
const excluded = (reason: string): Column => ({ excluded: reason });

interface ModelColumns {
  /** Prisma's generated scalar-field enum: the live column list. */
  scalarFields: Record<string, string>;
  /** Path from the export root to the record object that carries the columns. */
  path: readonly string[];
  columns: Record<string, Column>;
}

/** Requires an entry for exactly the model's scalar fields, at compile time. */
function model<const F extends string>(
  scalarFields: Record<string, F>,
  path: readonly string[],
  columns: Record<F, Column>
): ModelColumns {
  return { scalarFields, path, columns };
}

