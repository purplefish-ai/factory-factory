import { describe, expect, it, vi } from 'vitest';
import { JobRunner } from '@/backend/services/job-runner.service';
import { WorkspaceMetadataOrchestrator } from './workspace-metadata.orchestrator';

function setup() {
  let now = 1000;
  const history = [{ type: 'user' as const, content: 'Fix login errors', timestamp: '1' }];
  const result = {
    title: 'Fix login errors',
    branch: 'login-errors',
    summary: 'Investigating login errors.',
    sidebarSummary: 'Investigating login',
  };
  const dependencies = {
    findSession: vi.fn().mockResolvedValue({
      id: 's',
      workspaceId: 'w',
      provider: 'CODEX',
      codexAccountId: 'account',
    }),
    history: vi.fn(() => [...history]),
    findWorkspace: vi.fn().mockResolvedValue({
      id: 'w',
      projectId: 'p',
      name: 'fix-login-errors',
      status: 'READY',
      creationSource: 'MANUAL',
      creationMetadata: { autoGeneratedName: 'fix-login-errors' },
      conversationSummary: null,
    }),
    reserve: vi.fn().mockResolvedValue(true),
    accept: vi.fn().mockResolvedValue({ id: 'w', name: result.title, updatedAt: new Date(1000) }),
    generate: vi.fn().mockResolvedValue(result),
    publish: vi.fn(),
    now: () => now,
  };
  const service = new WorkspaceMetadataOrchestrator(dependencies, new JobRunner());
  return {
    service,
    dependencies,
    history,
    result,
    advance: (ms: number) => {
      now += ms;
    },
  };
}
const signal = () => new AbortController().signal;
describe('workspace metadata orchestration', () => {
  it('keeps newer activity when asynchronous session lookups resolve out of order', async () => {
    const { service, dependencies, history } = setup();
    let resolve!: (value: {
      id: string;
      workspaceId: string;
      provider: string;
      codexAccountId: string;
    }) => void;
    dependencies.findSession.mockImplementationOnce(
      () =>
        new Promise((done) => {
          resolve = done;
        })
    );
    const older = service.schedule('s');
    history.push({ type: 'user', content: 'New objective', timestamp: '2' });
    await service.schedule('s');
    resolve({ id: 's', workspaceId: 'w', provider: 'CODEX', codexAccountId: 'account' });
    await older;
    await service.run(signal());
    expect(dependencies.generate).toHaveBeenCalledWith(
      expect.objectContaining({
        input: expect.objectContaining({
          messages: expect.arrayContaining([expect.objectContaining({ content: 'New objective' })]),
        }),
      }),
      expect.any(AbortSignal)
    );
  });
  it('retains the captured final turn when session cleanup has evicted live history', async () => {
    const { service, dependencies } = setup();
    await service.schedule('s');
    dependencies.history.mockReturnValue([]);
    await service.run(signal());
    expect(dependencies.accept).toHaveBeenCalledTimes(1);
  });
  it('invalidates an in-flight summary when a new user message arrives in another session', async () => {
    const { service, dependencies, result } = setup();
    let resolve!: (value: typeof result) => void;
    dependencies.generate.mockImplementationOnce(
      () =>
        new Promise((done) => {
          resolve = done;
        })
    );
    await service.schedule('s', true);
    const work = service.run(signal());
    await vi.waitFor(() => expect(dependencies.generate).toHaveBeenCalled());
    dependencies.findSession.mockResolvedValue({
      id: 'other',
      workspaceId: 'w',
      provider: 'CODEX',
      codexAccountId: 'account',
    });
    await service.schedule('other', true);
    resolve(result);
    await work;
    expect(dependencies.accept).not.toHaveBeenCalled();
  });

  it('does not publish after a newer turn arrives while the database write is pending', async () => {
    const { service, dependencies, history } = setup();
    let finish!: (value: { id: string; name: string; updatedAt: Date }) => void;
    dependencies.accept.mockImplementationOnce(
      () =>
        new Promise((done) => {
          finish = done;
        })
    );
    await service.schedule('s');
    const work = service.run(signal());
    await vi.waitFor(() => expect(dependencies.accept).toHaveBeenCalled());
    history.push({ type: 'user', content: 'New objective', timestamp: '2' });
    await service.schedule('s');
    finish({ id: 'w', name: 'Login fix', updatedAt: new Date() });
    await work;
    expect(dependencies.publish).not.toHaveBeenCalled();
  });

  it('rechecks the call throttle for a replacement queued before inference started', async () => {
    const { service, dependencies, history } = setup();
    let reserve!: (value: boolean) => void;
    dependencies.reserve.mockImplementationOnce(
      () =>
        new Promise((done) => {
          reserve = done;
        })
    );
    await service.schedule('s');
    const work = service.run(signal());
    await vi.waitFor(() => expect(dependencies.reserve).toHaveBeenCalled());
    history.push({ type: 'user', content: 'A newer turn', timestamp: '2' });
    await service.schedule('s');
    reserve(true);
    await work;
    await service.run(signal());
    expect(dependencies.generate).toHaveBeenCalledTimes(1);
  });
  it('routes to the existing provider/account and publishes validated metadata', async () => {
    const { service, dependencies } = setup();
    await service.schedule('s');
    await service.run(signal());
    expect(dependencies.generate).toHaveBeenCalledWith(
      expect.objectContaining({ provider: 'CODEX', codexAccountId: 'account' }),
      expect.any(AbortSignal)
    );
    expect(dependencies.accept).toHaveBeenCalledWith(
      expect.objectContaining({ rename: true, sourceSessionId: 's' })
    );
    expect(dependencies.publish).toHaveBeenCalledTimes(1);
  });
  it('coalesces updates and runs the final pending turn after the throttle without another event', async () => {
    const { service, dependencies, history, advance } = setup();
    await service.schedule('s');
    await service.run(signal());
    history.push({ type: 'user', content: 'Test it', timestamp: '2' });
    await service.schedule('s');
    await service.run(signal());
    expect(dependencies.generate).toHaveBeenCalledTimes(1);
    advance(120_000);
    await service.run(signal());
    expect(dependencies.generate).toHaveBeenCalledTimes(2);
    await service.run(signal());
    expect(dependencies.generate).toHaveBeenCalledTimes(2);
  });
  it('rejects inference superseded by another completed turn', async () => {
    const { service, dependencies, history, result, advance } = setup();
    let resolve!: (value: typeof result) => void;
    dependencies.generate.mockImplementationOnce(
      () =>
        new Promise((done) => {
          resolve = done;
        })
    );
    await service.schedule('s');
    const work = service.run(signal());
    await vi.waitFor(() => expect(dependencies.generate).toHaveBeenCalled());
    history.push({ type: 'user', content: 'Changed direction', timestamp: '2' });
    await service.schedule('s');
    resolve(result);
    await work;
    expect(dependencies.accept).not.toHaveBeenCalled();
    advance(120_000);
    await service.run(signal());
    expect(dependencies.accept).toHaveBeenCalledTimes(1);
  });
  it('keeps existing data on failure, backs off, and stops on abort', async () => {
    const { service, dependencies, advance } = setup();
    dependencies.generate.mockRejectedValueOnce(new Error('not authenticated'));
    await service.schedule('s');
    await service.run(signal());
    expect(dependencies.accept).not.toHaveBeenCalled();
    await service.run(signal());
    expect(dependencies.generate).toHaveBeenCalledTimes(1);
    advance(120_000);
    const controller = new AbortController();
    controller.abort();
    await service.run(controller.signal);
    expect(dependencies.generate).toHaveBeenCalledTimes(1);
    await service.run(signal());
    expect(dependencies.accept).toHaveBeenCalledTimes(1);
  });
  it('does not rename explicit titles, and drops archived workspaces', async () => {
    const { service, dependencies, advance } = setup();
    dependencies.findWorkspace.mockResolvedValueOnce({
      id: 'w',
      projectId: 'p',
      name: 'My manual title',
      status: 'READY',
      creationSource: 'MANUAL',
      conversationSummary: null,
    });
    await service.schedule('s');
    await service.run(signal());
    expect(dependencies.accept).toHaveBeenCalledWith(expect.objectContaining({ rename: false }));
    dependencies.findWorkspace.mockResolvedValue({
      id: 'w',
      projectId: 'p',
      name: 'Archived',
      status: 'ARCHIVED',
      creationSource: 'MANUAL',
      conversationSummary: null,
    });
    advance(120_000);
    dependencies.reserve.mockClear();
    await service.schedule('s');
    await service.run(signal());
    expect(dependencies.generate).toHaveBeenCalledTimes(1);
    expect(dependencies.reserve).not.toHaveBeenCalled();
  });

  it('avoids transcript and database work on subsequent initial-message notifications while invalidating pending work', async () => {
    const { service, dependencies, history, result, advance } = setup();
    await service.schedule('s', true);
    await service.run(signal());
    history.push({ type: 'user', content: 'New turn', timestamp: '2' });
    await service.schedule('s');
    advance(120_000);
    let resolve!: (value: typeof result) => void;
    dependencies.generate.mockImplementationOnce(
      () =>
        new Promise((done) => {
          resolve = done;
        })
    );
    const work = service.run(signal());
    await vi.waitFor(() => expect(dependencies.generate).toHaveBeenCalledTimes(2));
    dependencies.history.mockClear();
    dependencies.findSession.mockClear();
    dependencies.accept.mockClear();
    await service.schedule('s', true);
    expect(dependencies.history).not.toHaveBeenCalled();
    expect(dependencies.findSession).not.toHaveBeenCalled();
    resolve(result);
    await work;
    expect(dependencies.accept).not.toHaveBeenCalled();
  });
});
