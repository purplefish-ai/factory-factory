async function restoreWithoutMetadata(backup: ReturnType<typeof exportDataSchema.parse>) {
  expect(backup.data.workspaces[0]).not.toHaveProperty('conversationMetadata');
  await clearIntegrationDatabase(db.prisma);
  const result = await dataBackupService.importData(backup);
  expect(result.workspaces).toEqual({ imported: 1, skipped: 0 });
  expect(await db.prisma.workspace.findUnique({ where: { id: 'workspace' } })).toMatchObject({
    name: 'Historical login fix',
    branchName: 'fix-login',
    status: 'READY',
  });
  expect(await db.prisma.workspaceMetadata.count()).toBe(0);
}

it('imports a metadata-free version 4 wire backup and converts its flattened PR', async () => {
  const backup = exportDataSchema.parse(historicalBackup(4, { ...workspaceWire, ...flatPRWire }));
  expect(backup.meta.schemaVersion).toBe(6);
  expect(backup.data.workspaces[0]?.prs).toEqual([
    expect.objectContaining({ id: 'legacy-pr-workspace', number: 42, hasMergeConflict: true }),
  ]);
  expect(backup.data.agentSessions[0]?.workspacePrId).toBe('legacy-pr-workspace');
  await restoreWithoutMetadata(backup);
  expect(await db.prisma.workspacePR.findMany({ where: { workspaceId: 'workspace' } })).toEqual([
    expect.objectContaining({
      id: 'legacy-pr-workspace',
      url: 'https://github.com/org/repo/pull/42',
      number: 42,
      state: 'OPEN',
      reviewState: 'APPROVED',
      ciStatus: 'SUCCESS',
      hasMergeConflict: true,
      syncedAt: new Date(historicalDate),
      reviewLastCommentId: 'review-comment',
    }),
  ]);
  expect(await db.prisma.agentSession.findUnique({ where: { id: 'legacy-fixer' } })).toMatchObject({
    workspacePrId: 'legacy-pr-workspace',
    providerSessionId: 'provider-login',
    codexAccountId: null,
  });
  expect(
    await db.prisma.workspacePRMonitoring.findUnique({ where: { workspaceId: 'workspace' } })
  ).toMatchObject({
    enabled: true,
    deliveryPauseReason: 'LEGACY_FIXER',
    legacySessionIds: ['legacy-fixer'],
  });
});

it('imports a metadata-free published version 5 wire backup and normalizes per-PR ratchet data', async () => {
  const backup = exportDataSchema.parse(
    historicalBackup(
      5,
      {
        ...workspaceWire,
        ratchetActivePrId: 'pr-42',
        prs: [
          {
            ...collectionPRWire,
            ratchet: {
              lastCheckedAt: historicalDate,
              activeSessionId: 'legacy-fixer',
              dispatchSnapshotKey: 'legacy-dispatch',
              dispatchOutcome: 'RUNNING',
              dispatchRetryCount: 1,
              dispatchStalled: false,
            },
          },
        ],
      },
      'pr-42'
    )
  );
  expect(backup.meta.schemaVersion).toBe(6);
  expect(backup.data.workspaces[0]?.ratchetActiveSessionId).toBeNull();
  expect(backup.data.workspaces[0]?.prs[0]).not.toHaveProperty('ratchet');
  expect(backup.data.workspaces[0]?.prMonitoring).toMatchObject({
    enabled: true,
    recipientSessionId: null,
    deliveryPauseReason: 'LEGACY_FIXER',
    legacySessionIds: ['legacy-fixer'],
  });
  await restoreWithoutMetadata(backup);
  expect(await db.prisma.workspacePR.findMany({ where: { workspaceId: 'workspace' } })).toEqual([
    expect.objectContaining({ id: 'pr-42', number: 42, title: 'Fix login', revision: 2 }),
  ]);
  expect(
    await db.prisma.workspacePRMonitoring.findUnique({ where: { workspaceId: 'workspace' } })
  ).toMatchObject({
    enabled: true,
    recipientSessionId: null,
    deliveryPauseReason: 'LEGACY_FIXER',
    legacySessionIds: ['legacy-fixer'],
  });
  expect(await db.prisma.agentSession.findUnique({ where: { id: 'legacy-fixer' } })).toMatchObject({
    workspacePrId: 'pr-42',
    status: 'COMPLETED',
    codexAccountId: null,
  });
});

