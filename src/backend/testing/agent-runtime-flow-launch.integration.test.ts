/** Replace only the ACP transport; each fake provider joins the flow's collection. */
async function fakeTransport(flow: RuntimeFlow) {
  const factory = await vi.importActual<
    typeof import('@/backend/services/session/service/acp/acp-client-factory')
  >('@/backend/services/session/service/acp/acp-client-factory');
  const { AcpNativeSessionTracker } = await vi.importActual<
    typeof import('@/backend/services/session/service/acp/acp-native-session-tracker')
  >('@/backend/services/session/service/acp/acp-native-session-tracker');
  vi.spyOn(factory.AcpClientFactory.prototype, 'createClient').mockImplementation(({ options }) => {
    const provider = fakeEventProvider(
      flow.session.AcpProcessHandle,
      options,
      undefined,
      new AcpNativeSessionTracker()
    );
    flow.providers.add(provider);
    return Promise.resolve(provider.handle);
  });
}

let db: IntegrationDatabase;
let f: RuntimeFlow;
/** Work a simulated process death left suspended; released only at teardown. */
let suspended: ReturnType<typeof deferred<never>>[];
beforeAll(async () => {
  await preloadEventFixtureModules();
}, 60_000);
beforeEach(async () => {
  db = await createIntegrationDatabase();
  suspended = [];
  f = await createRuntimeFlow(db);
  await fakeTransport(f);
}, 30_000);
afterEach(async () => {
  vi.useRealTimers();
  for (const hold of suspended) {
    hold.reject(new Error('The suspended process is gone'));
  }
  try {
    await f?.teardown();
  } finally {
    await destroyIntegrationDatabase(db);
  }
});

async function startedRun(number: number) {
  const owner = await f.save([f.trigger()]);
  await f.enable(owner);
  await f.arrive(githubEvent(`event-${number}`, { number }));
  await f.evaluate();
  return owner;
}
const onlyRun = async () => (await f.db.prisma.agentRun.findMany())[0]!;
/** A process death: suspend the current owner forever, then let its lease lapse. */
function suspend() {
  const hold = deferred<never>();
  suspended.push(hold);
  return hold.promise;
}
function afterLease() {
  vi.useFakeTimers({ toFake: ['Date'] });
  vi.setSystemTime(Date.now() + 61_000);
}

// Child settlement states, the stale-observation race and the 20-link cap are covered in
// src/backend/testing/event-run-child-rest.integration.test.ts.
it('holds a run while its child works and settles with the child PR once the child rests', async () => {
  const owner = await startedRun(81);
  await f.providers.waitForProviders(1);
  const parent = f.providers.providers[0]!;
  await parent.called;
  const run = await onlyRun();
  const creation = new f.workspace.WorkspaceCreationService({ logger: createLogger('flow') });
  const child = await creation.create({
    type: 'CHILD_WORKSPACE',
    projectId: owner.projectId,
    parentWorkspaceId: run.reservedWorkspaceId!,
    name: 'Child',
  });
  await f.workspace.workspaceStateMachine.startProvisioning(child.id);
  await f.workspace.workspaceRunScriptService.registerInitializedWorktree(child.id, {
    worktreePath: join(db.tempDir, child.id),
    branchName: `child-${child.id}`,
    isAutoGeneratedBranch: false,
    runScriptCommand: null,
    runScriptPostRunCommand: null,
    runScriptCleanupCommand: null,
  });
  await f.workspace.workspaceStateMachine.markReady(child.id);
  const chat = await f.session.sessionDataService.createAgentSession({
    workspaceId: child.id,
    workflow: 'followup',
    provider: 'CLAUDE',
    name: 'Child chat',
  });
  await f.session.sessionLifecycleService.startSession(chat.id, { initialPrompt: '' });
  const childTurn = f.session.sessionService.sendSessionMessage(chat.id, 'Child work');
  void childTurn.catch(() => undefined);
  await f.providers.waitForProviders(2);
  const childProvider = f.providers.providers[1]!;
  await childProvider.called;
  await f.workspace.workspacePrSnapshotService.attach(
    child.id,
    'https://github.com/org/repo/pull/900'
  );

  parent.response.resolve({ stopReason: 'end_turn' });
  await f.delivered(run.id);
  await f.step('maintain');
  expect((await f.caller.runs(owner)).items).toEqual([
    expect.objectContaining({ id: run.id, status: 'RUNNING', launchPhase: 'ACTIVE' }),
  ]);

  childProvider.response.resolve({ stopReason: 'end_turn' });
  await childTurn;
  await f.step('maintain');
  expect((await f.caller.runs(owner)).items).toEqual([
    expect.objectContaining({
      id: run.id,
      status: 'PR_CREATED',
      launchPhase: 'FINISHED',
      result: expect.objectContaining({
        pullRequests: [{ url: 'https://github.com/org/repo/pull/900', number: 900 }],
      }),
    }),
  ]);
  expect(await f.counts()).toMatchObject({ runs: 1, workspaces: 2 });
  expect(parent.connection.prompt).toHaveBeenCalledOnce();
});

it('settles a run held by a child that never starts once the 24-hour deadline passes', async () => {
  const owner = await startedRun(82);
  await f.providers.waitForProviders(1);
  await f.providers.providers[0]!.called;
  const run = await onlyRun();
  const creation = new f.workspace.WorkspaceCreationService({ logger: createLogger('flow') });
  await creation.create({
    type: 'CHILD_WORKSPACE',
    projectId: owner.projectId,
    parentWorkspaceId: run.reservedWorkspaceId!,
    name: 'Idle child',
  });
  await f.finishTurn(0);
  await f.delivered(run.id);
  await f.step('maintain');
  expect((await f.caller.runs(owner)).items[0]).toMatchObject({ status: 'RUNNING' });

  // The clock jumps as over a sleeping laptop: the in-memory lease lapses, so maintenance
  // releases the run and then adopts it for observation before it can settle it.
  const maintain = async () => {
    for (let pass = 0; pass < 3; pass++) {
      await f.step('maintain');
    }
  };
  vi.useFakeTimers({ toFake: ['Date'] });
  vi.setSystemTime(Date.now() + 24 * 60 * 60 * 1000 - 60_000);
  await maintain();
  expect((await f.caller.runs(owner)).items[0]).toMatchObject({ status: 'RUNNING' });
  vi.setSystemTime(Date.now() + 2 * 60_000);
  await maintain();
  expect((await f.caller.runs(owner)).items[0]).toMatchObject({
    status: 'COMPLETED',
    reasonCode: 'CHILD_HOLD_EXPIRED',
  });
});

// Overlapping and shifted pages are covered in
// src/backend/services/agent-definition/service/agent-source-poll-overlap.integration.test.ts.
it('delivers a repeated feed row once: one event, run, workspace, session and send', async () => {
  const owner = await startedRun(83);
  await f.step('poll');
  await f.evaluate();
  const { connection } = f;
  // The same provider event delivered again, as a re-read page or a replay would.
  expect(
    await f.owner.ingestEvent({
      connectionId: connection.id,
      providerEventId: 'event-83',
      payload: githubEvent('event-83', { number: 83 }).payload!,
    })
  ).toMatchObject({ duplicate: true });
  await f.step('poll');
  await f.evaluate(2);
  await f.finishTurn(0);
  await f.delivered((await onlyRun()).id);
  await f.step('maintain');
  await f.evaluate(2);
  await f.step('maintain');
  expect(await f.counts()).toMatchObject({
    events: 1,
    evaluations: 1,
    runs: 1,
    workspaces: 1,
    sessions: 1,
    prompts: 1,
  });
  expect((await f.caller.runs(owner)).items).toEqual([
    expect.objectContaining({ status: 'COMPLETED' }),
  ]);
});

// The full boundary matrix (workspace, session and link handoffs; SETUP and STARTUP
// preparation; SENDING and ACCEPTED takeover) is covered against the launch owner in
// src/backend/testing/event-launch.integration.test.ts and
// src/backend/testing/event-launch-recovery.integration.test.ts. These cases restart
// the composed runtime itself.
it.each(['claim committed', 'workspace created', 'session created'] as const)(
  'resumes after a restart once the %s, without a second workspace, session or send',
  async (boundary) => {
    if (boundary === 'claim committed') {
      // The claim transaction commits, then the process dies before the handoff.
      vi.spyOn(f.admission.applicationUpdateAdmission, 'run').mockImplementationOnce(async () => {
        await f.owner.claimNextRun();
        return await suspend();
      });
    } else if (boundary === 'workspace created') {
      const create = f.workspace.WorkspaceCreationService.prototype.createEventWorkspaceOnce;
      vi.spyOn(
        f.workspace.WorkspaceCreationService.prototype,
        'createEventWorkspaceOnce'
      ).mockImplementationOnce(async function (
        this: InstanceType<typeof f.workspace.WorkspaceCreationService>,
        source
      ) {
        await create.call(this, source);
        return await suspend();
      });
    } else {
      const create = f.session.sessionDataService.createEventSessionOnce.bind(
        f.session.sessionDataService
      );
      vi.spyOn(f.session.sessionDataService, 'createEventSessionOnce').mockImplementationOnce(
        async (input) => {
          await create(input);
          return await suspend();
        }
      );
    }
    const owner = await f.save([f.trigger()]);
    await f.enable(owner);
    await f.arrive(githubEvent('event-84', { number: 84 }));
    // The claim case suspends the evaluation job itself; the others suspend the launch.
    void f.evaluate().catch(() => undefined);
    const reached = {
      'claim committed': async () =>
        expect(await f.db.prisma.agentRun.count({ where: { status: 'RUNNING' } })).toBe(1),
      'workspace created': async () => expect(await f.db.prisma.workspace.count()).toBe(1),
      'session created': async () => expect(await f.db.prisma.agentSession.count()).toBe(1),
    }[boundary];
    await vi.waitFor(reached);
    const run = await onlyRun();
    expect(await f.counts()).toMatchObject({ prompts: 0 });

    f.boot();
    afterLease();
    await f.step('maintain');
    await f.finishTurn(0);
    await f.delivered(run.id);
    await f.step('maintain');
    expect((await f.caller.runs(owner)).items).toEqual([
      expect.objectContaining({ id: run.id, status: 'COMPLETED', attemptCount: 1 }),
    ]);
    await f.evaluate(2);
    await f.step('maintain');
    expect(await f.counts()).toMatchObject({ runs: 1, workspaces: 1, sessions: 1, prompts: 1 });
  }
);

it('surfaces an uncertain send as needing attention and never sends again, across a restart', async () => {
  const owner = await startedRun(85);
  await f.providers.waitForProviders(1);
  const provider = f.providers.providers[0]!;
  await provider.called;
  const run = await onlyRun();
  // The transport fails after the request left: the provider may have received it.
  provider.response.reject(new Error('Transport disconnected'));
  await f.delivered(run.id, 'AMBIGUOUS');
  await f.step('maintain');
  const attention = expect.objectContaining({
    id: run.id,
    status: 'RUNNING',
    launchPhase: 'NEEDS_ATTENTION',
    delivery: expect.objectContaining({ state: 'AMBIGUOUS' }),
  });
  expect((await f.caller.runs(owner)).items).toEqual([attention]);
  expect(
    await f.caller.recoveryTarget({
      projectId: owner.projectId,
      agentId: owner.agentId,
      runId: run.id,
    })
  ).toMatchObject({ status: 'AVAILABLE', run: expect.anything() });

  f.boot();
  afterLease();
  await f.step('maintain');
  await f.evaluate(2);
  await f.step('maintain');
  expect((await f.caller.runs(owner)).items).toEqual([attention]);
  expect(provider.connection.prompt).toHaveBeenCalledOnce();
  expect(await f.counts()).toMatchObject({ runs: 1, workspaces: 1, sessions: 1, prompts: 1 });
});
