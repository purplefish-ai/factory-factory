import type { Prisma } from '@prisma-gen/client';
export interface CreateWorkspaceInput {
  projectId: string;
  name: string;
  description?: string;
  branchName?: string;
  githubIssueNumber?: number;
  githubIssueUrl?: string;
  linearIssueId?: string;
  linearIssueIdentifier?: string;
  linearIssueUrl?: string;
  isAutoGeneratedBranch?: boolean;
  ratchetEnabled?: boolean;
  defaultSessionProvider?: Prisma.WorkspaceCreateInput['defaultSessionProvider'];
  creationSource?:
    | 'MANUAL'
    | 'RESUME_BRANCH'
    | 'GITHUB_ISSUE'
    | 'LINEAR_ISSUE'
    | 'EVENT_AGENT'
    | 'PERIODIC_TASK'
    | 'CHILD_WORKSPACE';
  creationMetadata?: Prisma.InputJsonValue;
  periodicTaskId?: string;
  parentWorkspaceId?: string;
}

export interface UpdateWorkspaceInput {
  name?: string;
  description?: string;
  // Note: status changes must go through workspaceStateMachine, not direct updates
  worktreePath?: string | null;
  branchName?: string | null;
  isAutoGeneratedBranch?: boolean;
  githubIssueNumber?: number | null;
  githubIssueUrl?: string | null;
  // The PR cache lives on WorkspacePR; see workspacePrAccessor.
  // PR monitoring configuration lives on WorkspacePRMonitoring.
  defaultSessionProvider?: Prisma.WorkspaceUpdateInput['defaultSessionProvider'];
  // Activity tracking
  hasHadSessions?: boolean;
  // The run-script group lives on WorkspaceRunScript; see workspaceRunScriptAccessor.
}
