import { afterAll, afterEach, beforeAll, expect, it, vi } from 'vitest';
import {
  clearIntegrationDatabase,
  createIntegrationDatabase,
  destroyIntegrationDatabase,
  type IntegrationDatabase,
} from '@/backend/testing/integration-db';

let db: IntegrationDatabase;
let workspaceAccessor: typeof import('./workspace.accessor').workspaceAccessor;

beforeAll(async () => {
  db = await createIntegrationDatabase();
  ({ workspaceAccessor } =
    await vi.importActual<typeof import('./workspace.accessor')>('./workspace.accessor'));
}, 30_000);
afterEach(async () => {
  await db.prisma.workspace.deleteMany();
  await clearIntegrationDatabase(db.prisma);
});
afterAll(async () => {
  await destroyIntegrationDatabase(db);
});

const worktree = {
  worktreePath: '/worktrees/initialized',
  branchName: 'feature',
  isAutoGeneratedBranch: false,
};
const commands = {
  runScriptCommand: 'pnpm dev',
  runScriptPostRunCommand: 'pnpm watch',
  runScriptCleanupCommand: 'pnpm clean',
};

async function createWorkspace() {
  const project = await db.prisma.project.create({
    data: { name: 'P', slug: 'p', repoPath: '/repo', worktreeBasePath: '/worktrees' },
  });
  return workspaceAccessor.create({ projectId: project.id, name: 'Initialized' });
}

it('registers the worktree columns and cached commands together', async () => {
  const workspace = await createWorkspace();

  await workspaceAccessor.registerInitializedWorktree(workspace.id, worktree, commands);

  expect(await db.prisma.workspace.findUnique({ where: { id: workspace.id } })).toMatchObject(
    worktree
  );
  expect(
    await db.prisma.workspaceRunScript.findUnique({ where: { workspaceId: workspace.id } })
  ).toMatchObject({
    command: 'pnpm dev',
    postRunCommand: 'pnpm watch',
    cleanupCommand: 'pnpm clean',
  });
});

it('leaves the worktree unregistered when its commands cannot be written', async () => {
  const workspace = await createWorkspace();
  await db.prisma.workspaceRunScript.delete({ where: { workspaceId: workspace.id } });

  await expect(
    workspaceAccessor.registerInitializedWorktree(workspace.id, worktree, commands)
  ).rejects.toThrow('WorkspaceRunScript row not found');

  expect(await db.prisma.workspace.findUnique({ where: { id: workspace.id } })).toMatchObject({
    worktreePath: null,
    branchName: null,
  });
});
