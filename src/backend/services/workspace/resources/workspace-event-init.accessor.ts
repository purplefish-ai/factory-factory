import { prisma } from '@/backend/db';
import { ApplicationError } from '@/backend/lib/application-error';
import { agentClaimResultSchema, type AgentClaimResult } from '@/shared/agent-runtime';
import type { Prisma } from '@prisma-gen/client';
import {
  workspaceRunScriptAccessor,
  type RunScriptCommandFields,
} from './workspace-run-script.accessor';

export type EventWorkspaceClaim = Extract<AgentClaimResult, { status: 'CLAIMED' }>;
export class EventWorkspaceFenceError extends ApplicationError {
  constructor() {
    super('CONFLICT', 'Event workspace initialization is no longer current');
  }
}
async function current(tx: Prisma.TransactionClient, claim: EventWorkspaceClaim) {
  const run = await tx.agentRun.findUnique({
    where: { id: claim.runId },
    include: { initialDelivery: true, agentDefinition: { select: { projectId: true } } },
  });
  const workspace = await tx.workspace.findUnique({
    where: { id: claim.reservedWorkspaceId },
    include: { project: true },
  });
  const origin = await tx.workspaceLaunchOrigin.findUnique({ where: { runId: claim.runId } });
  const session = await tx.agentSession.findUnique({ where: { id: claim.reservedSessionId } });
  const sessionOrigin = await tx.agentSessionLaunchOrigin.findUnique({
    where: { runId: claim.runId },
  });
  if (
    !(run && workspace && origin && session && sessionOrigin) ||
    run.status !== 'RUNNING' ||
    !['PROVISIONING', 'READY'].includes(run.launchPhase) ||
    run.workerGeneration !== claim.workerGeneration ||
    run.attemptGeneration !== claim.attemptGeneration ||
    run.reservedWorkspaceId !== claim.reservedWorkspaceId ||
    run.reservedSessionId !== claim.reservedSessionId ||
    run.initialMessageId !== claim.initialMessageId ||
    run.initialDelivery?.state !== 'PENDING' ||
    run.initialDelivery.attemptGeneration !== claim.attemptGeneration ||
    !run.leaseExpiresAt ||
    run.leaseExpiresAt <= new Date() ||
    workspace.creationSource !== 'EVENT_AGENT' ||
    workspace.project.isArchived ||
    ['ARCHIVING', 'ARCHIVED'].includes(workspace.status) ||
    workspace.projectId !== run.agentDefinition.projectId ||
    origin.workspaceId !== workspace.id ||
    origin.projectId !== workspace.projectId ||
    session.workspaceId !== workspace.id ||
    sessionOrigin.workspaceId !== workspace.id ||
    sessionOrigin.sessionId !== session.id
  ) {
    throw new EventWorkspaceFenceError();
  }
  return workspace;
}
/** The workspace owner locks before the foreign identity read; it never writes the run/session. */
function owned<T>(
  input: EventWorkspaceClaim,
  operation: (
    tx: Prisma.TransactionClient,
    workspace: Awaited<ReturnType<typeof current>>
  ) => Promise<T>,
  assertCurrent?: () => void
) {
  const claim = agentClaimResultSchema.options[0].parse(input);
  return prisma.$transaction(async (tx) => {
    await tx.$executeRaw`UPDATE "Workspace" SET "updatedAt" = "updatedAt" WHERE 0`;
    const workspace = await current(tx, claim);
    assertCurrent?.();
    const result = await operation(tx, workspace);
    assertCurrent?.();
    return result;
  });
}
export const workspaceEventInitAccessor = {
  read: (claim: EventWorkspaceClaim, assertCurrent?: () => void) =>
    owned(claim, async (_tx, row) => row, assertCurrent),
  start(claim: EventWorkspaceClaim, assertCurrent?: () => void) {
    return owned(
      claim,
      async (tx, row) => {
        if (row.status === 'READY' && row.worktreePath) {
          return { previous: row.status, workspace: row };
        }
        const workspace = await tx.workspace.update({
          where: { id: row.id },
          data: {
            status: 'PROVISIONING',
            initStartedAt: new Date(),
            initCompletedAt: null,
            initErrorMessage: null,
            initOutput: null,
            initScriptPid: null,
          },
        });
        return { previous: row.status, workspace };
      },
      assertCurrent
    );
  },
  register(
    claim: EventWorkspaceClaim,
    data: { worktreePath: string; branchName: string | null; isAutoGeneratedBranch: boolean },
    commands: RunScriptCommandFields,
    assertCurrent?: () => void
  ) {
    return owned(
      claim,
      async (tx, row) => {
        if (row.status !== 'PROVISIONING') {
          throw new EventWorkspaceFenceError();
        }
        await tx.workspace.update({ where: { id: row.id }, data });
        await workspaceRunScriptAccessor.writeCommands(row.id, commands, tx);
      },
      assertCurrent
    );
  },
  finish(
    claim: EventWorkspaceClaim,
    status: 'READY' | 'FAILED',
    message?: string,
    assertCurrent?: () => void
  ) {
    return owned(
      claim,
      async (tx, row) => {
        if (row.status !== 'PROVISIONING') {
          throw new EventWorkspaceFenceError();
        }
        const workspace = await tx.workspace.update({
          where: { id: row.id },
          data: {
            status,
            initCompletedAt: new Date(),
            initScriptPid: null,
            initErrorMessage: message?.slice(0, 2000) ?? null,
          },
        });
        return { previous: row.status, workspace };
      },
      assertCurrent
    );
  },
  appendOutput(claim: EventWorkspaceClaim, text: string, assertCurrent?: () => void) {
    return owned(
      claim,
      async (tx, row) => {
        if (row.status !== 'PROVISIONING') {
          throw new EventWorkspaceFenceError();
        }
        await tx.workspace.update({
          where: { id: row.id },
          data: { initOutput: `${row.initOutput ?? ''}${text}`.slice(-50 * 1024) },
        });
      },
      assertCurrent
    );
  },
  scriptPid(claim: EventWorkspaceClaim, pid: number, clear: boolean, assertCurrent?: () => void) {
    return owned(
      claim,
      async (tx, row) => {
        if (row.status !== 'PROVISIONING') {
          throw new EventWorkspaceFenceError();
        }
        await tx.workspace.updateMany({
          where: { id: row.id, ...(clear ? { initScriptPid: pid } : {}) },
          data: { initScriptPid: clear ? null : pid },
        });
      },
      assertCurrent
    );
  },
};
