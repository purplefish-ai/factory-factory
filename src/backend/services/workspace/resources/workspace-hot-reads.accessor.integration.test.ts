import { afterAll, beforeAll, expect, it, vi } from 'vitest';
import {
  createIntegrationDatabase,
  destroyIntegrationDatabase,
  type IntegrationDatabase,
} from '@/backend/testing/integration-db';
import type { PrismaClient } from '@prisma-gen/client';
import { workspaceDetailReadAccessor } from './workspace-detail-read.accessor';
import { workspaceMetadataAccessor } from './workspace-metadata.accessor';
import { workspaceAccessor } from './workspace.accessor';

const database = vi.hoisted(() => ({ prisma: undefined as PrismaClient | undefined }));
vi.mock('@/backend/db', () => ({
  get prisma() {
    return database.prisma;
  },
}));

// One large base64 attachment, a long startup log, a provider config snapshot
// and a PR observation with review bodies: the blobs hot reads must not load.
const attachmentData = 'A'.repeat(2 * 1024 * 1024);
const creationMetadata = {
  initialPrompt: 'Describe this screenshot',
  autoGeneratedName: 'Attachments',
  initialAttachments: [
    { id: 'a', name: 'shot.png', type: 'image/png', size: 1, data: attachmentData },
  ],
};

let db: IntegrationDatabase;
beforeAll(async () => {
  db = await createIntegrationDatabase();
  database.prisma = db.prisma;
  await db.prisma.project.create({
    data: { id: 'p', name: 'P', slug: 'p', repoPath: '/tmp/p', worktreeBasePath: '/tmp/w' },
  });
  await db.prisma.workspace.create({
    data: {
      id: 'w',
      projectId: 'p',
      name: 'Attachments',
      status: 'READY',
      creationSource: 'MANUAL',
      initOutput: 'installing...\n'.repeat(3000),
      creationMetadata,
      agentSessions: {
        create: {
          id: 's',
          workflow: 'implement',
          provider: 'CLAUDE',
          providerMetadata: { configSnapshot: { blob: 'x'.repeat(64 * 1024) } },
        },
      },
      prs: {
        create: {
          id: 'pr',
          url: 'https://github.com/o/r/pull/1',
          number: 1,
          state: 'OPEN',
          observation: { reviews: [{ body: 'r'.repeat(64 * 1024) }] },
        },
      },
    },
  });
}, 30_000);
afterAll(async () => {
  await destroyIntegrationDatabase(db);
});

const hotReads = [
  ['findById', async () => [await workspaceAccessor.findById('w')]],
  ['findByProjectIdWithSessions', () => workspaceAccessor.findByProjectIdWithSessions('p')],
  [
    'findAllNonArchivedWithSessionsAndProject',
    () => workspaceAccessor.findAllNonArchivedWithSessionsAndProject(),
  ],
] as const;

it.each(hotReads)('%s leaves out every blob column', async (_name, read) => {
  const rows = await read();

  expect(rows).toHaveLength(1);
  const [row] = rows;
  expect(row).toMatchObject({
    id: 'w',
    name: 'Attachments',
    prNumber: 1,
    agentSessions: [expect.objectContaining({ id: 's', workflow: 'implement' })],
  });
  expect(row).not.toHaveProperty('creationMetadata');
  expect(row).not.toHaveProperty('initOutput');
  expect(row?.agentSessions[0]).not.toHaveProperty('providerMetadata');
  expect(JSON.stringify(row).length).toBeLessThan(16 * 1024);
});

it('keeps the stored PR observation while workspace reads serialize PRs without it', async () => {
  const pr = await db.prisma.workspacePR.findUniqueOrThrow({ where: { id: 'pr' } });
  expect(pr.observation).not.toBeNull();

  const row = await workspaceAccessor.findById('w');
  expect(row?.prs).toEqual([expect.objectContaining({ id: 'pr', number: 1 })]);
  expect(row?.prs[0]).not.toHaveProperty('observation');
});

it('serves creation metadata only through the separately named finders', async () => {
  await expect(workspaceDetailReadAccessor.findInitialMessageContext('w')).resolves.toEqual({
    id: 'w',
    parentWorkspaceId: null,
    creationMetadata,
  });
  await expect(
    workspaceDetailReadAccessor.findInitialMessageContext('missing')
  ).resolves.toBeNull();

  await expect(workspaceMetadataAccessor.findContext('w')).resolves.toEqual({
    id: 'w',
    projectId: 'p',
    name: 'Attachments',
    status: 'READY',
    creationSource: 'MANUAL',
    creationMetadata,
    conversationSummary: null,
  });
  await expect(workspaceMetadataAccessor.findContext('missing')).resolves.toBeNull();
});

it('reads non-object creation metadata as no initial message context', async () => {
  await db.prisma.workspace.create({
    data: { id: 'list', projectId: 'p', name: 'List', creationMetadata: ['not', 'an', 'object'] },
  });

  await expect(workspaceDetailReadAccessor.findInitialMessageContext('list')).resolves.toEqual({
    id: 'list',
    parentWorkspaceId: null,
    creationMetadata: null,
  });
  await db.prisma.workspace.delete({ where: { id: 'list' } });
});
