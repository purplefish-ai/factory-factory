import { afterAll, beforeAll, expect, it, vi } from 'vitest';
import {
  createIntegrationDatabase,
  destroyIntegrationDatabase,
  type IntegrationDatabase,
} from '@/backend/testing/integration-db';
import type { PrismaClient } from '@prisma-gen/client';
import { workspaceMetadataAccessor } from './workspace-metadata.accessor';

const database = vi.hoisted(() => ({ prisma: undefined as PrismaClient | undefined }));
vi.mock('@/backend/db', () => ({
  get prisma() {
    return database.prisma;
  },
}));
let db: IntegrationDatabase;
beforeAll(async () => {
  db = await createIntegrationDatabase();
  database.prisma = db.prisma;
  await db.prisma.project.create({
    data: { id: 'p', name: 'P', slug: 'p', repoPath: '/tmp/p', worktreeBasePath: '/tmp/w' },
  });
}, 30_000);
afterAll(async () => {
  await destroyIntegrationDatabase(db);
});
const result = {
  title: 'Fix login race',
  branch: 'login-race',
  summary: 'Testing the login fix.',
  sidebarSummary: 'Testing login',
};
it('rolls back summaries and names invalidated while acceptance is in progress', async () => {
  await workspace('superseded-write');
  await workspaceMetadataAccessor.reserve('superseded-write', 'r');
  let checks = 0;
  const accepted = await workspaceMetadataAccessor.accept({
    workspaceId: 'superseded-write',
    requestId: 'r',
    expectedName: 'fix-the-login',
    rename: true,
    result,
    sourceSessionId: 's',
    sourceMessageId: 'm',
    generatedAt: new Date(),
    isCurrent: () => ++checks === 1,
  });
  expect(accepted).toBeNull();
  expect(
    await db.prisma.workspaceMetadata.findUnique({ where: { workspaceId: 'superseded-write' } })
  ).toMatchObject({ generatedAt: null, summary: null });
  expect(await db.prisma.workspace.findUnique({ where: { id: 'superseded-write' } })).toMatchObject(
    { name: 'fix-the-login' }
  );
});
async function workspace(id: string) {
  await db.prisma.workspace.create({
    data: {
      id,
      projectId: 'p',
      name: 'fix-the-login',
      status: 'READY',
      creationMetadata: { autoGeneratedName: 'fix-the-login' },
    },
  });
}
function save(workspaceId: string, requestId: string) {
  return workspaceMetadataAccessor.accept({
    workspaceId,
    requestId,
    expectedName: 'fix-the-login',
    rename: true,
    result,
    sourceSessionId: 's',
    sourceMessageId: 'm',
    generatedAt: new Date(),
  });
}
it('persists metadata, renames once, and preserves the first branch suggestion', async () => {
  await workspace('one');
  await workspaceMetadataAccessor.reserve('one', 'r1');
  expect(await save('one', 'r1')).toMatchObject({ name: 'Fix login race' });
  await workspaceMetadataAccessor.reserve('one', 'r2');
  await workspaceMetadataAccessor.accept({
    workspaceId: 'one',
    requestId: 'r2',
    expectedName: 'Fix login race',
    rename: true,
    result: { ...result, title: 'Different title', branch: 'different-branch' },
    sourceSessionId: 's',
    sourceMessageId: 'm2',
    generatedAt: new Date(),
  });
  expect(await db.prisma.workspace.findUnique({ where: { id: 'one' } })).toMatchObject({
    name: 'Fix login race',
  });
  expect(
    await db.prisma.workspaceMetadata.findUnique({ where: { workspaceId: 'one' } })
  ).toMatchObject({ branch: 'login-race', sourceMessageId: 'm2' });
});
it('keeps a manual rename made while inference is pending', async () => {
  await workspace('manual');
  await workspaceMetadataAccessor.reserve('manual', 'r');
  await db.prisma.workspace.update({ where: { id: 'manual' }, data: { name: 'My chosen title' } });
  expect(await save('manual', 'r')).toMatchObject({ name: 'My chosen title' });
});

it('pins a manual title even when the chosen text equals the generated placeholder', async () => {
  await workspace('pinned');
  await workspaceMetadataAccessor.reserve('pinned', 'r');
  await workspaceMetadataAccessor.renameAndPin('pinned', 'fix-the-login');
  expect(await save('pinned', 'r')).toMatchObject({ name: 'fix-the-login' });
});
it('rejects superseded requests and archived workspaces', async () => {
  await workspace('stale');
  await workspaceMetadataAccessor.reserve('stale', 'old');
  await workspaceMetadataAccessor.reserve('stale', 'new');
  expect(await save('stale', 'old')).toBeNull();
  await db.prisma.workspace.update({ where: { id: 'stale' }, data: { status: 'ARCHIVED' } });
  expect(await save('stale', 'new')).toBeNull();
  expect(await workspaceMetadataAccessor.reserve('stale', 'later')).toBe(false);
});
