import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';
import { z } from 'zod';
import {
  createIntegrationDatabase,
  destroyIntegrationDatabase,
  type IntegrationDatabase,
} from '@/backend/testing/integration-db';
import { Prisma, type PrismaClient } from '@prisma-gen/client';
import { workspaceMetadataAccessor } from './workspace-metadata.accessor';

const database = vi.hoisted(() => ({ prisma: undefined as PrismaClient | undefined }));
vi.mock('@/backend/db', () => ({
  get prisma() {
    return database.prisma;
  },
}));
let db: IntegrationDatabase;
beforeAll(async () => {
  db = await createIntegrationDatabase();
  database.prisma = db.prisma;
  await db.prisma.project.create({
    data: { id: 'p', name: 'P', slug: 'p', repoPath: '/tmp/p', worktreeBasePath: '/tmp/w' },
  });
}, 30_000);
afterAll(async () => {
  await destroyIntegrationDatabase(db);
});
const result = {
  title: 'Fix login race',
  branch: 'login-race',
  summary: 'Testing the login fix.',
  sidebarSummary: 'Testing login',
};
it('rolls back summaries and names invalidated while acceptance is in progress', async () => {
  await workspace('superseded-write');
  await workspaceMetadataAccessor.reserve('superseded-write', 'r');
  let checks = 0;
  const accepted = await workspaceMetadataAccessor.accept({
    workspaceId: 'superseded-write',
    requestId: 'r',
    expectedName: 'fix-the-login',
    rename: true,
    result,
    sourceSessionId: 's',
    sourceMessageId: 'm',
    generatedAt: new Date(),
    // Permit the entry guard, then invalidate at the post-write guard to exercise rollback.
    isCurrent: () => ++checks === 1,
  });
  expect(accepted).toBeNull();
  expect(
    await db.prisma.workspaceMetadata.findUnique({ where: { workspaceId: 'superseded-write' } })
  ).toMatchObject({ generatedAt: null, summary: null });
  expect(await db.prisma.workspace.findUnique({ where: { id: 'superseded-write' } })).toMatchObject(
    { name: 'fix-the-login' }
  );
});
async function workspace(id: string) {
  await db.prisma.workspace.create({
    data: {
      id,
      projectId: 'p',
      name: 'fix-the-login',
      status: 'READY',
      creationMetadata: { autoGeneratedName: 'fix-the-login' },
    },
  });
}
function save(workspaceId: string, requestId: string) {
  return workspaceMetadataAccessor.accept({
    workspaceId,
    requestId,
    expectedName: 'fix-the-login',
    rename: true,
    result,
    sourceSessionId: 's',
    sourceMessageId: 'm',
    generatedAt: new Date(),
  });
}
it('persists metadata, renames once, preserves the first branch suggestion and replaces summaries', async () => {
  await workspace('one');
  await workspaceMetadataAccessor.reserve('one', 'r1');
  expect(await save('one', 'r1')).toMatchObject({ name: 'Fix login race' });
  await workspaceMetadataAccessor.reserve('one', 'r2');
  await workspaceMetadataAccessor.accept({
    workspaceId: 'one',
    requestId: 'r2',
    expectedName: 'Fix login race',
    rename: true,
    result: {
      title: 'Different title',
      branch: 'different-branch',
      summary: 'Reviewing the login fix.',
      sidebarSummary: 'Reviewing login',
    },
    sourceSessionId: 's',
    sourceMessageId: 'm2',
    generatedAt: new Date(),
  });
  expect(await db.prisma.workspace.findUnique({ where: { id: 'one' } })).toMatchObject({
    name: 'Fix login race',
  });
  expect(
    await db.prisma.workspaceMetadata.findUnique({ where: { workspaceId: 'one' } })
  ).toMatchObject({
    title: 'Fix login race',
    branch: 'login-race',
    summary: 'Reviewing the login fix.',
    sidebarSummary: 'Reviewing login',
    sourceMessageId: 'm2',
  });
});
it('keeps a manual rename made while inference is pending', async () => {
  await workspace('manual');
  await workspaceMetadataAccessor.reserve('manual', 'r');
  await db.prisma.workspace.update({ where: { id: 'manual' }, data: { name: 'My chosen title' } });
  expect(await save('manual', 'r')).toMatchObject({ name: 'My chosen title' });
});

it('pins a manual title even when the chosen text equals the generated placeholder', async () => {
  await workspace('pinned');
  await workspaceMetadataAccessor.reserve('pinned', 'r');
  await workspaceMetadataAccessor.renameAndPin('pinned', 'fix-the-login');
  expect(await save('pinned', 'r')).toMatchObject({ name: 'fix-the-login' });
});
describe('renameAndPin', () => {
  const attachment = { name: 'screenshot.png', data: 'A'.repeat(512 * 1024) };
  const storedRowSchema = z.array(
    z.object({ metadata: z.string().nullable(), storage: z.string(), writes: z.coerce.number() })
  );

  beforeAll(async () => {
    // Count every UPDATE that assigns the column, whether or not its value changes.
    await db.prisma.$executeRawUnsafe(
      'CREATE TABLE "PinMetadataWrite" ("workspaceId" TEXT NOT NULL)'
    );
    await db.prisma.$executeRawUnsafe(
      'CREATE TRIGGER "pin_metadata_write" AFTER UPDATE OF "creationMetadata" ON "Workspace" BEGIN INSERT INTO "PinMetadataWrite" VALUES (NEW."id"); END'
    );
  });
  afterAll(async () => {
    await db.prisma.$executeRawUnsafe('DROP TRIGGER "pin_metadata_write"');
    await db.prisma.$executeRawUnsafe('DROP TABLE "PinMetadataWrite"');
  });

  async function pinWorkspace(
    id: string,
    creationMetadata?: Prisma.InputJsonValue | typeof Prisma.JsonNull
  ) {
    await db.prisma.workspace.create({
      data: { id, projectId: 'p', name: 'generated', status: 'READY', creationMetadata },
    });
  }
  async function stored(id: string) {
    const [row] = storedRowSchema.parse(
      await db.prisma
        .$queryRaw`SELECT CAST("creationMetadata" AS TEXT) AS "metadata", typeof("creationMetadata") AS "storage", (SELECT count(*) FROM "PinMetadataWrite" WHERE "workspaceId" = ${id}) AS "writes" FROM "Workspace" WHERE "id" = ${id}`
    );
    return row;
  }

  it('drops only the generated-name key and returns the row without its blobs', async () => {
    await pinWorkspace('pin-drop', {
      initialPrompt: 'Fix the login',
      autoGeneratedName: 'generated',
      initialAttachments: [attachment],
      nested: { autoGeneratedName: 'kept', emoji: '✓ é' },
    });
    const before = await db.prisma.workspace.findUniqueOrThrow({ where: { id: 'pin-drop' } });

    const renamed = await workspaceMetadataAccessor.renameAndPin('pin-drop', 'Chosen');

    expect(Object.keys(renamed).sort()).toEqual(['id', 'name', 'status', 'updatedAt']);
    expect(renamed).toMatchObject({ id: 'pin-drop', name: 'Chosen', status: 'READY' });
    expect(renamed.updatedAt.getTime()).toBeGreaterThanOrEqual(before.updatedAt.getTime());
    const after = await db.prisma.workspace.findUniqueOrThrow({ where: { id: 'pin-drop' } });
    expect(after.creationMetadata).toStrictEqual({
      initialPrompt: 'Fix the login',
      initialAttachments: [attachment],
      nested: { autoGeneratedName: 'kept', emoji: '✓ é' },
    });
    expect(Object.keys(z.record(z.string(), z.unknown()).parse(after.creationMetadata))).toEqual([
      'initialPrompt',
      'initialAttachments',
      'nested',
    ]);
    expect(await stored('pin-drop')).toMatchObject({ storage: 'text', writes: 1 });
  });

  it('leaves metadata without a generated name unwritten', async () => {
    await pinWorkspace('pin-absent', { initialAttachments: [attachment] });
    await pinWorkspace('pin-sql-null');
    await pinWorkspace('pin-json-null', Prisma.JsonNull);
    await pinWorkspace('pin-array', ['autoGeneratedName']);
    const before = await Promise.all(
      ['pin-absent', 'pin-sql-null', 'pin-json-null', 'pin-array'].map(stored)
    );

    for (const id of ['pin-absent', 'pin-sql-null', 'pin-json-null', 'pin-array']) {
      await expect(workspaceMetadataAccessor.renameAndPin(id, 'Chosen')).resolves.toMatchObject({
        name: 'Chosen',
      });
    }

    expect(
      await Promise.all(['pin-absent', 'pin-sql-null', 'pin-json-null', 'pin-array'].map(stored))
    ).toEqual(before);
    expect(before.map((row) => row?.storage)).toEqual(['text', 'null', 'text', 'text']);
    expect(before.map((row) => row?.writes)).toEqual([0, 0, 0, 0]);
  });

  it('rejects a missing workspace', async () => {
    await expect(workspaceMetadataAccessor.renameAndPin('pin-missing', 'Chosen')).rejects.toThrow(
      Prisma.PrismaClientKnownRequestError
    );
  });
});
it('rejects superseded requests and archived workspaces', async () => {
  await workspace('stale');
  await workspaceMetadataAccessor.reserve('stale', 'old');
  await workspaceMetadataAccessor.reserve('stale', 'new');
  expect(await save('stale', 'old')).toBeNull();
  await db.prisma.workspace.update({ where: { id: 'stale' }, data: { status: 'ARCHIVED' } });
  expect(await save('stale', 'new')).toBeNull();
  expect(await workspaceMetadataAccessor.reserve('stale', 'later')).toBe(false);
});
it('rejects metadata for a workspace that is archiving', async () => {
  await workspace('archiving');
  await workspaceMetadataAccessor.reserve('archiving', 'r');
  await db.prisma.workspace.update({ where: { id: 'archiving' }, data: { status: 'ARCHIVING' } });
  expect(await save('archiving', 'r')).toBeNull();
  expect(await workspaceMetadataAccessor.reserve('archiving', 'later')).toBe(false);
});
