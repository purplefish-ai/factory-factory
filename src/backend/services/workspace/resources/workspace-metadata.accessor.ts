import { z } from 'zod';
import { prisma } from '@/backend/db';
import {
  WorkspaceConversationSummarySchema,
  type WorkspaceMetadataResult,
} from '@/shared/workspace-conversation-summary';
import type { WorkspaceMetadata } from '@prisma-gen/client';

class SupersededMetadataWrite extends Error {}

const autoGeneratedNameRowsSchema = z.array(z.object({ autoGeneratedName: z.unknown() }));

export function projectConversationSummary(row?: WorkspaceMetadata | null) {
  if (!row?.generatedAt) {
    return null;
  }
  const parsed = WorkspaceConversationSummarySchema.safeParse({
    ...row,
    generatedAt: row.generatedAt.toISOString(),
  });
  return parsed.success ? parsed.data : null;
}

export const workspaceMetadataAccessor = {
  /**
   * The fields metadata generation reads before accepting a result. The
   * auto-generated name is projected in SQLite so the read does not load the
   * rest of `creationMetadata`, which can hold base64 initial attachments.
   */
  async findContext(workspaceId: string) {
    const row = await prisma.workspace.findUnique({
      where: { id: workspaceId },
      select: {
        id: true,
        projectId: true,
        name: true,
        status: true,
        creationSource: true,
        conversationMetadata: true,
      },
    });
    if (!row) {
      return null;
    }
    const [provenance] = autoGeneratedNameRowsSchema.parse(
      await prisma.$queryRaw`SELECT json_extract("creationMetadata", '$.autoGeneratedName') AS "autoGeneratedName" FROM "Workspace" WHERE "id" = ${workspaceId}`
    );
    const autoGeneratedName = provenance?.autoGeneratedName;
    const { conversationMetadata, ...rest } = row;
    return {
      ...rest,
      autoGeneratedName: typeof autoGeneratedName === 'string' ? autoGeneratedName : null,
      conversationSummary: projectConversationSummary(conversationMetadata),
    };
  },
  /**
   * Renames the workspace and pins the name by dropping
   * `creationMetadata.autoGeneratedName`. SQLite removes the key in place, so
   * the rest of `creationMetadata`, which can hold base64 initial attachments,
   * is neither loaded nor re-serialised here, and rows without the key keep
   * their stored value.
   */
  renameAndPin(workspaceId: string, name: string) {
    return prisma.$transaction(async (tx) => {
      const workspace = await tx.workspace.update({
        where: { id: workspaceId },
        data: { name },
        select: { id: true, name: true, status: true, updatedAt: true },
      });
      await tx.$executeRaw`UPDATE "Workspace" SET "creationMetadata" = json_remove("creationMetadata", '$.autoGeneratedName') WHERE "id" = ${workspaceId} AND json_type("creationMetadata", '$.autoGeneratedName') IS NOT NULL`;
      return workspace;
    });
  },
  reserve(workspaceId: string, requestId: string): Promise<boolean> {
    return prisma.$transaction(async (tx) => {
      const workspace = await tx.workspace.findFirst({
        where: { id: workspaceId, status: { notIn: ['ARCHIVING', 'ARCHIVED'] } },
        select: { id: true },
      });
      if (!workspace) {
        return false;
      }
      await tx.workspaceMetadata.upsert({
        where: { workspaceId },
        create: { workspaceId, requestId },
        update: { requestId },
      });
      return true;
    });
  },

  accept(input: {
    workspaceId: string;
    requestId: string;
    expectedName: string;
    rename: boolean;
    result: WorkspaceMetadataResult;
    sourceSessionId: string;
    sourceMessageId: string;
    generatedAt: Date;
    isCurrent?: () => boolean;
  }) {
    return prisma
      .$transaction(async (tx) => {
        if (input.isCurrent?.() === false) {
          return null;
        }
        const workspace = await tx.workspace.findFirst({
          where: { id: input.workspaceId, status: { notIn: ['ARCHIVING', 'ARCHIVED'] } },
        });
        const previous = await tx.workspaceMetadata.findUnique({
          where: { workspaceId: input.workspaceId },
        });
        if (!workspace || previous?.requestId !== input.requestId) {
          return null;
        }
        const first = !previous.generatedAt;
        await tx.workspaceMetadata.update({
          where: { workspaceId: input.workspaceId },
          data: {
            title: first ? input.result.title : previous.title,
            branch: first ? input.result.branch : previous.branch,
            summary: input.result.summary,
            sidebarSummary: input.result.sidebarSummary,
            generatedAt: input.generatedAt,
            sourceSessionId: input.sourceSessionId,
            sourceMessageId: input.sourceMessageId,
          },
        });
        const provenance = z
          .object({ autoGeneratedName: z.string() })
          .safeParse(workspace.creationMetadata);
        const accepted =
          first &&
          input.rename &&
          provenance.success &&
          provenance.data.autoGeneratedName === workspace.name &&
          workspace.name === input.expectedName
            ? await tx.workspace.update({
                where: { id: workspace.id },
                data: { name: input.result.title },
              })
            : workspace;
        if (input.isCurrent?.() === false) {
          throw new SupersededMetadataWrite();
        }
        return accepted;
      })
      .catch((error: unknown) => {
        if (error instanceof SupersededMetadataWrite) {
          return null;
        }
        throw error;
      });
  },
};
