import { afterAll, afterEach, beforeAll, expect, it, vi } from 'vitest';
import {
  clearIntegrationDatabase,
  createIntegrationDatabase,
  destroyIntegrationDatabase,
  type IntegrationDatabase,
} from '@/backend/testing/integration-db';

let db: IntegrationDatabase;
let data: typeof import('./data.service').workspaceDataService;
beforeAll(async () => {
  db = await createIntegrationDatabase();
  ({ workspaceDataService: data } =
    await vi.importActual<typeof import('./data.service')>('./data.service'));
}, 30_000);
afterEach(async () => {
  await db.prisma.$executeRawUnsafe('DROP TRIGGER IF EXISTS reject_discovery_reset');
  await clearIntegrationDatabase(db.prisma);
});
afterAll(async () => {
  await destroyIntegrationDatabase(db);
});
async function fixture() {
  const project = await db.prisma.project.create({
    data: {
      name: 'Branch acceptance',
      slug: 'branches',
      repoPath: '/repo',
      worktreeBasePath: '/worktrees',
    },
  });
  const workspace = await db.prisma.workspace.create({
    data: {
      projectId: project.id,
      name: 'Workspace',
      status: 'READY',
      branchName: 'old',
      isAutoGeneratedBranch: true,
    },
  });
  await db.prisma.workspacePRDiscovery.create({
    data: { workspaceId: workspace.id, nextCheckAt: new Date(1000) },
  });
  return workspace;
}
it('returns and delivers the committed transaction row after discovery reset', async () => {
  const workspace = await fixture();
  const accepted: unknown[] = [];
  const unsubscribe = data.subscribeAcceptedBranch((row) => accepted.push(row));
  try {
    const result = await data.setBranchNameAndClearAutoGenerated(workspace.id, 'new');
    const persisted = await db.prisma.workspace.findUniqueOrThrow({ where: { id: workspace.id } });
    expect(result).toEqual({
      id: workspace.id,
      branchName: 'new',
      status: 'READY',
      updatedAt: persisted.updatedAt,
    });
    expect(accepted).toEqual([result]);
    expect(persisted.isAutoGeneratedBranch).toBe(false);
    expect(
      await db.prisma.workspacePRDiscovery.findUniqueOrThrow({
        where: { workspaceId: workspace.id },
      })
    ).toMatchObject({ nextCheckAt: null });
  } finally {
    unsubscribe();
  }
});
it('rolls back the branch and emits no accepted fact when discovery reset fails', async () => {
  const workspace = await fixture();
  await db.prisma.$executeRawUnsafe(
    `CREATE TRIGGER reject_discovery_reset BEFORE UPDATE ON WorkspacePRDiscovery BEGIN SELECT RAISE(ABORT, 'discovery reset failed'); END`
  );
  const accepted = vi.fn();
  const unsubscribe = data.subscribeAcceptedBranch(accepted);
  try {
    await expect(
      data.setBranchNameAndClearAutoGenerated(workspace.id, 'rejected')
    ).rejects.toMatchObject({
      code: 'P2003',
      meta: {
        modelName: 'WorkspacePRDiscovery',
        driverAdapterError: {
          cause: {
            originalCode: 'SQLITE_CONSTRAINT_TRIGGER',
            originalMessage: 'discovery reset failed',
          },
        },
      },
    });
    expect(
      await db.prisma.workspace.findUniqueOrThrow({ where: { id: workspace.id } })
    ).toMatchObject({
      branchName: 'old',
      isAutoGeneratedBranch: true,
      updatedAt: workspace.updatedAt,
    });
    expect(accepted).not.toHaveBeenCalled();
    await db.prisma.$executeRawUnsafe('DROP TRIGGER reject_discovery_reset');
    await data.setBranchNameAndClearAutoGenerated(workspace.id, 'retry');
    expect(accepted).toHaveBeenCalledOnce();
    await db.prisma.workspace.delete({ where: { id: workspace.id } });
    await expect(
      data.setBranchNameAndClearAutoGenerated(workspace.id, 'deleted')
    ).rejects.toMatchObject({ code: 'P2025' });
    expect(accepted).toHaveBeenCalledOnce();
  } finally {
    unsubscribe();
  }
});
