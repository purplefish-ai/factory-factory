import type { RunScriptExecutionUpdate } from '@/backend/services/workspace/resources/workspace-run-script.accessor';
import {
  type RunScriptExecutionState,
  workspaceAccessor,
} from '@/backend/services/workspace/resources/workspace.accessor';
import type { RunScriptStatus } from '@/shared/core';
import type { WorkspaceInitGuard } from '@/shared/workspace-init-retry';

class WorkspaceRunScriptService {
  registerInitializedWorktree(
    workspaceId: string,
    data: {
      worktreePath: string;
      branchName: string | null;
      isAutoGeneratedBranch: boolean;
      runScriptCommand: string | null;
      runScriptPostRunCommand: string | null;
      runScriptCleanupCommand: string | null;
    },
    guard?: WorkspaceInitGuard
  ) {
    return workspaceAccessor.registerInitializedWorktree(
      workspaceId,
      {
        worktreePath: data.worktreePath,
        branchName: data.branchName,
        isAutoGeneratedBranch: data.isAutoGeneratedBranch,
      },
      {
        runScriptCommand: data.runScriptCommand,
        runScriptPostRunCommand: data.runScriptPostRunCommand,
        runScriptCleanupCommand: data.runScriptCleanupCommand,
      },
      ...(guard ? ([guard] as const) : [])
    );
  }

  setCommands(
    workspaceId: string,
    data: {
      runScriptCommand: string | null;
      runScriptPostRunCommand: string | null;
      runScriptCleanupCommand: string | null;
    },
    guard?: WorkspaceInitGuard
  ) {
    return workspaceAccessor.setRunScriptCommands(
      workspaceId,
      data,
      ...(guard ? ([guard] as const) : [])
    );
  }

  findExecutionState(workspaceId: string): Promise<RunScriptExecutionState | null> {
    return workspaceAccessor.findRunScriptExecutionState(workspaceId);
  }

  getExecutionStateOrThrow(workspaceId: string): Promise<RunScriptExecutionState> {
    return workspaceAccessor.findRunScriptExecutionStateOrThrow(workspaceId);
  }

  /**
   * The four process fields are picked out one by one rather than forwarded, so a
   * caller cannot smuggle a `Workspace` field through this transition. The column
   * mapping in `workspaceRunScriptAccessor` would drop one anyway now that the
   * write targets a table with no such column, but the narrowing is what the
   * boundary test asserts and it costs nothing: `undefined` means "not supplied"
   * on the way through, so a partial transition stays partial.
   */
  transitionStatusIfCurrent(
    workspaceId: string,
    currentStatus: RunScriptStatus,
    data: RunScriptExecutionUpdate
  ) {
    return workspaceAccessor.casRunScriptStatusUpdate(workspaceId, currentStatus, {
      runScriptStatus: data.runScriptStatus,
      runScriptPid: data.runScriptPid,
      runScriptPort: data.runScriptPort,
      runScriptStartedAt: data.runScriptStartedAt,
    });
  }

  recoverStaleStatuses() {
    return workspaceAccessor.resetStaleRunScriptStatuses();
  }

  clearInitOutput(workspaceId: string, guard?: WorkspaceInitGuard) {
    return workspaceAccessor.clearInitOutput(workspaceId, guard);
  }

  appendInitOutput(
    workspaceId: string,
    output: string,
    maxSize?: number,
    guard?: WorkspaceInitGuard
  ) {
    return workspaceAccessor.appendInitOutput(workspaceId, output, maxSize, guard);
  }

  setInitScriptPid(workspaceId: string, pid: number, guard?: WorkspaceInitGuard) {
    return workspaceAccessor.setInitScriptPid(workspaceId, pid, guard);
  }

  clearInitScriptPid(workspaceId: string, pid: number, guard?: WorkspaceInitGuard) {
    return workspaceAccessor.clearInitScriptPid(workspaceId, pid, guard);
  }
}

export const workspaceRunScriptService = new WorkspaceRunScriptService();
export type { RunScriptExecutionState, RunScriptExecutionUpdate };
