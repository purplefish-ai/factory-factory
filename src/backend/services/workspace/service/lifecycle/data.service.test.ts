import { beforeEach, describe, expect, it, vi } from 'vitest';

const { mockResetPRDiscoveryBackoff, mockUpdate, mockSetBranchName } = vi.hoisted(() => ({
  mockResetPRDiscoveryBackoff: vi.fn(),
  mockUpdate: vi.fn(),
  mockSetBranchName: vi.fn(),
}));

vi.mock('@/backend/services/workspace/resources/workspace.accessor', () => ({
  workspaceAccessor: {
    setBranchNameAndClearDiscoverySchedule: (...args: unknown[]) => mockSetBranchName(...args),
    update: (...args: unknown[]) => mockUpdate(...args),
  },
}));

vi.mock('@/backend/services/workspace/resources/workspace-pr.accessor', () => ({
  workspacePrAccessor: {
    resetDiscoveryBackoff: (...args: unknown[]) => mockResetPRDiscoveryBackoff(...args),
  },
}));

import { workspaceDataService } from './data.service';

beforeEach(() => {
  vi.clearAllMocks();
});

describe('workspaceDataService', () => {
  it('sets the branch name and clears the discovery schedule together', async () => {
    mockSetBranchName.mockResolvedValue({
      id: 'workspace-1',
      branchName: 'canonical',
      status: 'READY',
      updatedAt: new Date(100),
    });

    await workspaceDataService.setBranchNameAndClearAutoGenerated('workspace-1', 'my-custom-name');

    expect(mockSetBranchName).toHaveBeenCalledOnce();
    expect(mockSetBranchName).toHaveBeenCalledWith('workspace-1', 'my-custom-name');
  });

  it('delegates PR discovery backoff resets to the PR accessor', async () => {
    mockResetPRDiscoveryBackoff.mockResolvedValue(true);

    await expect(workspaceDataService.resetPRDiscoveryBackoff('workspace-1')).resolves.toBe(true);

    expect(mockResetPRDiscoveryBackoff).toHaveBeenCalledOnce();
    expect(mockResetPRDiscoveryBackoff).toHaveBeenCalledWith('workspace-1');
  });
});

it('delivers the canonical committed branch synchronously before resolving', async () => {
  const canonical = {
    id: 'workspace-1',
    branchName: 'canonical',
    status: 'READY',
    updatedAt: new Date(100),
  };
  mockSetBranchName.mockResolvedValue(canonical);
  const accepted: unknown[] = [];
  const unsubscribe = workspaceDataService.subscribeAcceptedBranch((row) => accepted.push(row));
  try {
    const result = await workspaceDataService.setBranchNameAndClearAutoGenerated(
      'workspace-1',
      'requested'
    );
    expect(accepted).toEqual([canonical]);
    expect(result).toEqual(canonical);
  } finally {
    unsubscribe();
  }
});

it('serializes acceptance through delivery per workspace while releasing failures', async () => {
  let release!: (row: unknown) => void;
  const first = { id: 'one', branchName: 'first', status: 'READY', updatedAt: new Date(100) };
  const second = { ...first, branchName: 'second' };
  const other = { ...first, id: 'other' };
  mockSetBranchName.mockImplementation((id, name) =>
    name === 'first'
      ? new Promise((resolve) => {
          release = resolve;
        })
      : name === 'fail'
        ? Promise.reject(new Error('rollback'))
        : Promise.resolve(id === 'other' ? other : second)
  );
  const accepted: unknown[] = [];
  const unsubscribe = workspaceDataService.subscribeAcceptedBranch((row) => accepted.push(row));
  try {
    const pending = workspaceDataService.setBranchNameAndClearAutoGenerated('one', 'first');
    const following = workspaceDataService.setBranchNameAndClearAutoGenerated('one', 'second');
    await workspaceDataService.setBranchNameAndClearAutoGenerated('other', 'first-other');
    expect(mockSetBranchName).not.toHaveBeenCalledWith('one', 'second');
    expect(accepted).toEqual([other]);
    release(first);
    await Promise.all([pending, following]);
    expect(accepted).toEqual([other, first, second]);
    await expect(
      workspaceDataService.setBranchNameAndClearAutoGenerated('one', 'fail')
    ).rejects.toThrow('rollback');
    await workspaceDataService.setBranchNameAndClearAutoGenerated('one', 'retry');
    expect(accepted).toEqual([other, first, second, second]);
  } finally {
    unsubscribe();
  }
});
