import { afterEach, expect, it, vi } from 'vitest';
import type { createLogger } from '@/backend/services/logger.service';
import { unsafeCoerce } from '@/test-utils/unsafe-coerce';
import { WorkspaceCreationService } from './creation.service';

const mocks = vi.hoisted(() => ({ create: vi.fn() }));
vi.mock('@/backend/services/settings', () => ({
  userSettingsService: { get: () => Promise.resolve({ ratchetEnabled: true }) },
}));
vi.mock('@/backend/services/workspace/resources/workspace.accessor', () => ({
  workspaceAccessor: { create: mocks.create },
}));
vi.mock('./state-machine.service', () => ({
  workspaceStateMachine: { publishCreated: vi.fn() },
}));
afterEach(() => vi.resetAllMocks());

it.each([
  { nameIsGenerated: true, initialPrompt: 'Fix login', expectedMarker: 'Initial name' },
  { nameIsGenerated: false, initialPrompt: 'Fix login', expectedMarker: undefined },
  { nameIsGenerated: true, initialPrompt: undefined, expectedMarker: undefined },
  { nameIsGenerated: true, initialPrompt: '', expectedMarker: undefined },
  { nameIsGenerated: true, initialPrompt: ' \n\t ', expectedMarker: undefined },
])(
  'requires generated-name provenance and a nonblank prompt: $nameIsGenerated / $initialPrompt',
  async ({ nameIsGenerated, initialPrompt, expectedMarker }) => {
    mocks.create.mockResolvedValue({ id: 'workspace' });
    const service = new WorkspaceCreationService({
      logger: unsafeCoerce<ReturnType<typeof createLogger>>({ debug: vi.fn() }),
    });

    await service.create({
      type: 'MANUAL',
      projectId: 'project',
      name: 'Initial name',
      nameIsGenerated,
      initialPrompt,
    });

    const metadata = mocks.create.mock.calls[0]![0].creationMetadata;
    if (expectedMarker) {
      expect(metadata).toMatchObject({ autoGeneratedName: expectedMarker, initialPrompt });
    } else {
      expect(metadata ?? {}).not.toHaveProperty('autoGeneratedName');
    }
  }
);
