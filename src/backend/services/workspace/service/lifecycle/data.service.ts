import { workspacePrAccessor } from '@/backend/services/workspace/resources/workspace-pr.accessor';
import { workspaceRatchetAccessor } from '@/backend/services/workspace/resources/workspace-ratchet.accessor';
import { workspaceAccessor } from '@/backend/services/workspace/resources/workspace.accessor';
import type { Workspace, WorkspaceProviderSelection } from '@prisma-gen/client';
import { AcceptedBranchPublisher, type AcceptedWorkspaceBranch } from './accepted-branch';

class WorkspaceDataService {
  private readonly acceptedBranches = new AcceptedBranchPublisher();

  subscribeAcceptedBranch(listener: (row: AcceptedWorkspaceBranch) => void): () => void {
    return this.acceptedBranches.subscribe(listener);
  }

  findById(id: string) {
    return workspaceAccessor.findById(id);
  }

  findByIdWithProject(id: string) {
    return workspaceAccessor.findByIdWithProject(id);
  }

  exists(id: string) {
    return workspaceAccessor.exists(id);
  }

  findProviderSelection(id: string) {
    return workspaceAccessor.findProviderSelection(id);
  }

  findFixerContext(id: string) {
    return workspaceAccessor.findFixerContext(id);
  }

  findStatusSnapshot(id: string) {
    return workspaceAccessor.findStatusSnapshot(id);
  }

  findPRContext(id: string) {
    return workspaceAccessor.findPRContext(id);
  }

  findPRState(id: string, prId?: string) {
    return workspacePrAccessor.findPRState(id, prId);
  }

  findRatchetProjection(id: string) {
    return workspaceRatchetAccessor.findSnapshotProjection(id);
  }

  findByProjectId(projectId: string) {
    return workspaceAccessor.findByProjectId(projectId);
  }

  findIssueLinksByProjectId(projectId: string) {
    return workspaceAccessor.findIssueLinksByProjectId(projectId);
  }

  findByIdsWithProject(ids: string[]) {
    return workspaceAccessor.findByIdsWithProject(ids);
  }

  recordSessionPresence(id: string): Promise<void> {
    return workspaceAccessor.markHasHadSessions(id);
  }

  setBranchNameAndClearAutoGenerated(id: string, branchName: string) {
    return this.acceptedBranches.accept(id, () =>
      workspaceAccessor.setBranchNameAndClearDiscoverySchedule(id, branchName)
    );
  }

  resetPRDiscoveryBackoff(id: string) {
    return workspacePrAccessor.resetDiscoveryBackoff(id);
  }

  clearAutoGeneratedBranch(id: string) {
    return workspaceAccessor.update(id, {
      isAutoGeneratedBranch: false,
    });
  }

  rename(id: string, name: string) {
    return workspaceAccessor.update(id, { name });
  }

  update(
    id: string,
    data: {
      defaultSessionProvider?: WorkspaceProviderSelection;
    }
  ) {
    return workspaceAccessor.update(id, {
      defaultSessionProvider: data.defaultSessionProvider,
    });
  }

  delete(id: string): Promise<Workspace> {
    return workspaceAccessor.delete(id);
  }
}

export const workspaceDataService = new WorkspaceDataService();
