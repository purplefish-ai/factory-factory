import { durableRecoverySchema } from '@/shared/schemas/durable-recovery.schema';
import type { Prisma } from '@prisma-gen/client';
import { readRecoveryJsonStorage } from './recovery-json-storage';

export async function readDurableRecovery(tx: Prisma.TransactionClient) {
  const rows = {
    jsonStorage: await readRecoveryJsonStorage(tx),
    agentSourceCheckpoint: await tx.agentSourceCheckpoint.findMany(),
    agentSourceHead: await tx.agentSourceHead.findMany(),
    chatIntent: await tx.chatIntent.findMany({ orderBy: { id: 'asc' } }),
    promptDispatchAttempt: await tx.promptDispatchAttempt.findMany({
      orderBy: { createdAt: 'asc' },
    }),
    periodicTask: await tx.periodicTask.findMany({
      select: {
        id: true,
        projectId: true,
        name: true,
        prompt: true,
        cadence: true,
        scheduledTime: true,
        timezone: true,
        scheduledDayOfMonth: true,
        isEnabled: true,
        nextRunAt: true,
        lastRunAt: true,
        createdAt: true,
        updatedAt: true,
      },
    }),
    periodicTaskExecution: await tx.periodicTaskExecution.findMany({
      select: {
        launchSnapshot: true,
        id: true,
        periodicTaskId: true,
        workspaceId: true,
        status: true,
        prUrl: true,
        prNumber: true,
        errorMessage: true,
        startedAt: true,
        completedAt: true,
      },
    }),
    agentDefinition: await tx.agentDefinition.findMany({
      select: {
        id: true,
        projectId: true,
        name: true,
        instructions: true,
        isEnabled: true,
        executionConfig: true,
        definitionRevision: true,
        managementRevision: true,
        createdAt: true,
        updatedAt: true,
      },
    }),
    agentConnection: await tx.agentConnection.findMany({
      select: {
        id: true,
        provider: true,
        externalId: true,
        name: true,
        isEnabled: true,
        createdAt: true,
        updatedAt: true,
      },
    }),
    agentTrigger: await tx.agentTrigger.findMany({
      select: {
        id: true,
        agentDefinitionId: true,
        type: true,
        connectionId: true,
        description: true,
        config: true,
        filterInstructions: true,
        isEnabled: true,
        isConfigured: true,
        triggerRevision: true,
        activationGeneration: true,
        activationState: true,
        activationBoundary: true,
        pendingActivation: true,
        createdAt: true,
        updatedAt: true,
      },
    }),
    agentRun: await tx.agentRun.findMany({
      select: {
        id: true,
        agentDefinitionId: true,
        triggerId: true,
        contextExpiredAt: true,
        idempotencyKey: true,
        status: true,
        eventId: true,
        definitionRevision: true,
        triggerRevision: true,
        activationGeneration: true,
        launchPhase: true,
        reservedWorkspaceId: true,
        reservedSessionId: true,
        initialMessageId: true,
        workerGeneration: true,
        attemptGeneration: true,
        attemptCount: true,
        nextAttemptAt: true,
        leaseExpiresAt: true,
        expiresAt: true,
        reasonCode: true,
        result: true,
        effectiveExecution: true,
        launchPreparation: true,
        definitionSnapshot: true,
        triggerSnapshot: true,
        input: true,
        workspaceId: true,
        errorMessage: true,
        createdAt: true,
        startedAt: true,
        completedAt: true,
      },
    }),
    agentProposal: await tx.agentProposal.findMany({
      select: {
        id: true,
        workspaceId: true,
        revision: true,
        specification: true,
        sourceNames: true,
        agentDefinitionId: true,
        createdAt: true,
        updatedAt: true,
      },
    }),
    agentSourceState: await tx.agentSourceState.findMany({
      select: {
        authorityRevision: true,
        lastSourceOrder: true,
        connectionId: true,
        isReady: true,
        cursor: true,
        health: true,
        lastObservedAt: true,
        updatedAt: true,
      },
    }),
    agentSourcePage: await tx.agentSourcePage.findMany({
      select: {
        id: true,
        connectionId: true,
        scanId: true,
        ordinal: true,
        phase: true,
        requestPage: true,
        nextPage: true,
        sourceOrder: true,
        evidence: true,
        createdAt: true,
      },
    }),
    agentSourceBaseline: await tx.agentSourceBaseline.findMany({
      select: {
        id: true,
        connectionId: true,
        headEventId: true,
        afterHeadEventId: true,
        sourceOrder: true,
        createdAt: true,
      },
    }),
    agentEvent: await tx.agentEvent.findMany({
      select: {
        id: true,
        connectionId: true,
        providerEventId: true,
        sourceOrder: true,
        payload: true,
        occurredAt: true,
        observedAt: true,
        payloadExpiresAt: true,
        identityExpiresAt: true,
        createdAt: true,
      },
    }),
    agentEvaluation: await tx.agentEvaluation.findMany({
      select: {
        id: true,
        eventId: true,
        connectionId: true,
        agentDefinitionId: true,
        triggerId: true,
        definitionRevision: true,
        triggerRevision: true,
        activationGeneration: true,
        status: true,
        reasonCode: true,
        explanation: true,
        attemptCount: true,
        nextAttemptAt: true,
        configurationSnapshot: true,
        classifier: true,
        runId: true,
        expiresAt: true,
        createdAt: true,
        updatedAt: true,
      },
    }),
    agentInitialDelivery: await tx.agentInitialDelivery.findMany({
      select: {
        id: true,
        runId: true,
        state: true,
        attemptGeneration: true,
        sendAttemptId: true,
        messageId: true,
        providerTurnId: true,
        evidence: true,
        sendingAt: true,
        acceptedAt: true,
        finishedAt: true,
        createdAt: true,
        updatedAt: true,
      },
    }),
    workspaceNotification: await tx.workspaceNotification.findMany({
      select: {
        recoveryHeld: true,
        id: true,
        workspaceId: true,
        sourceWorkspaceId: true,
        sourceWorkspaceName: true,
        sourceProjectName: true,
        message: true,
        direction: true,
        deliveredAt: true,
        createdAt: true,
      },
    }),
    workspaceLaunchOrigin: await tx.workspaceLaunchOrigin.findMany({
      select: {
        childHistoryVersion: true,
        runId: true,
        workspaceId: true,
        projectId: true,
        createdAt: true,
      },
    }),
    workspaceChildOrigin: await tx.workspaceChildOrigin.findMany({
      select: { parentWorkspaceId: true, childWorkspaceId: true, createdAt: true },
    }),
    agentSessionLaunchOrigin: await tx.agentSessionLaunchOrigin.findMany({
      select: { runId: true, sessionId: true, workspaceId: true, execution: true, createdAt: true },
    }),
    sessionLifecycleEvent: await tx.sessionLifecycleEvent.findMany({
      select: {
        id: true,
        workspaceId: true,
        sessionId: true,
        kind: true,
        reason: true,
        message: true,
        dedupeKey: true,
        createdAt: true,
      },
    }),
    decisionLog: await tx.decisionLog.findMany({
      select: {
        id: true,
        agentId: true,
        decision: true,
        reasoning: true,
        context: true,
        timestamp: true,
      },
    }),
  };
  return durableRecoverySchema.parse(JSON.parse(JSON.stringify(rows)));
}
