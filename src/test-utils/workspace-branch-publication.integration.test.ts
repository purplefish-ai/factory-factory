const persist = vi.hoisted(() => vi.fn());
vi.mock('@/backend/services/workspace/resources/workspace.accessor', () => ({
  workspaceAccessor: { setBranchNameAndClearDiscoverySchedule: persist },
}));
afterEach(() => {
  vi.clearAllMocks();
});

function fixture() {
  const store = new WorkspaceSnapshotStore();
  store.configure({
    deriveFlowState: (input) =>
      deriveWorkspaceFlowState({
        ...input,
        prUpdatedAt: input.prUpdatedAt ? new Date(input.prUpdatedAt) : null,
      }),
    deriveSidebarStatus: deriveWorkspaceSidebarStatus,
  });
  const baseline = makeCompleteWorkspaceSnapshotEntry({ branchName: 'old' });
  store.upsert(baseline.workspaceId, baseline, 'seed', 100);
  expect(store.getByWorkspaceId(baseline.workspaceId)?.summaryVersion).toBe(1);
  const workspaceEvents = new EventEmitter();
  const ratchet = new EventEmitter();
  const collector = createEventCollectorOrchestrator(
    unsafeCoerce<EventCollectorDependencies>({
      createLogger: () => ({ info: vi.fn(), debug: vi.fn(), warn: vi.fn(), error: vi.fn() }),
      prSnapshotService: new EventEmitter(),
      workspaceActivityService: new EventEmitter(),
      workspaceStateMachine: workspaceEvents,
      ratchetService: ratchet,
      runScriptStateMachine: new EventEmitter(),
      workspaceAutoIterationService: new EventEmitter(),
      sessionDomainService: new EventEmitter(),
      workspaceDataService,
      workspaceSnapshotStore: store,
    })
  );
  const accepted = (branchName: string, status = 'READY', time = 200) => ({
    id: baseline.workspaceId,
    branchName,
    status,
    updatedAt: new Date(time),
  });
  return { store, collector, workspaceEvents, ratchet, accepted, baseline };
}

it('publishes a committed branch immediately into complete list and detail stream projections', async () => {
  const { store, collector, accepted, baseline } = fixture();
  const client = new QueryClient({
    defaultOptions: { queries: { retry: false, gcTime: Infinity } },
  });
  const owner = getProjectWorkspaceCacheReconciler(client, baseline.projectId);
  const token = owner.beginConnection();
  const before = structuredClone(store.getByWorkspaceId(baseline.workspaceId)!);
  owner.apply(token, { type: 'snapshot_full', projectId: baseline.projectId, entries: [before] });
  const changes: SnapshotChangedEvent[] = [];
  store.on(SNAPSHOT_CHANGED, (event: SnapshotChangedEvent) => {
    changes.push(event);
    owner.apply(token, {
      type: 'snapshot_changed',
      workspaceId: event.workspaceId,
      entry: event.entry,
    });
  });
  collector.start();
  try {
    persist.mockResolvedValue(accepted('canonical'));
    await workspaceDataService.setBranchNameAndClearAutoGenerated(
      baseline.workspaceId,
      'requested'
    );
    expect(changes).toHaveLength(1);
    const options = projectWorkspaceQueryOptions(
      client,
      baseline.projectId,
      async (): Promise<ProjectWorkspaceCache> => ({
        workspaces: [projectSnapshotToWorkspace(before)],
        reviewCount: 0,
      })
    );
    await client.fetchQuery({ ...options, staleTime: 0 });
    expect(client.getQueryData(options.queryKey)).toMatchObject({
      workspaces: [{ branchName: 'canonical' }],
    });
    const detail = unsafeCoerce<Parameters<typeof owner.reconcileDetail>[0]>(
      projectSnapshotToWorkspace(before)
    );
    expect(owner.reconcileDetail(detail, owner.captureEpoch(), undefined)?.branchName).toBe(
      'canonical'
    );
    expect(JSON.stringify(changes)).not.toContain('branchUpdatedAt');
    expect(store.getByWorkspaceId(baseline.workspaceId)?.fieldTimestamps).toEqual(
      before.fieldTimestamps
    );
  } finally {
    collector.stop();
    store.clear();
    client.clear();
  }
});

it('uses collector lifetime without duplicate listeners, and ignores canonical archived rows', async () => {
  const { store, collector, accepted, baseline } = fixture();
  const changed = vi.fn();
  store.on(SNAPSHOT_CHANGED, changed);
  collector.start();
  collector.start();
  try {
    persist.mockResolvedValue(accepted('one'));
    await workspaceDataService.setBranchNameAndClearAutoGenerated(baseline.workspaceId, 'one');
    expect(changed).toHaveBeenCalledOnce();
    collector.stop();
    persist.mockResolvedValue(accepted('while stopped', 'READY', 300));
    await workspaceDataService.setBranchNameAndClearAutoGenerated(baseline.workspaceId, 'two');
    expect(changed).toHaveBeenCalledOnce();
    collector.start();
    for (const status of ['ARCHIVING', 'ARCHIVED']) {
      persist.mockResolvedValue(accepted('archived', status, 400));
      await workspaceDataService.setBranchNameAndClearAutoGenerated(
        baseline.workspaceId,
        'archived'
      );
    }
    expect(changed).toHaveBeenCalledOnce();
    persist.mockResolvedValue(accepted('after restart', 'READY', 500));
    await workspaceDataService.setBranchNameAndClearAutoGenerated(baseline.workspaceId, 'three');
    expect(changed).toHaveBeenCalledTimes(2);
  } finally {
    collector.stop();
    store.clear();
  }
});

it.each([100, 200])(
  'late lifecycle provenance %s cannot undo an accepted branch or suppress READY',
  async (provenance) => {
    const { store, collector, workspaceEvents, accepted, baseline } = fixture();
    collector.start();
    try {
      store.upsert(baseline.workspaceId, { status: 'PROVISIONING' }, 'status', 300);
      persist.mockResolvedValue(accepted('canonical'));
      await workspaceDataService.setBranchNameAndClearAutoGenerated(
        baseline.workspaceId,
        'requested'
      );
      workspaceEvents.emit(WORKSPACE_STATE_CHANGED, {
        workspaceId: baseline.workspaceId,
        fromStatus: 'PROVISIONING',
        toStatus: 'READY',
        workspace: {
          ...baseline,
          updatedAt: new Date(provenance),
          createdAt: new Date(baseline.createdAt),
          branchName: 'old',
        },
      });
      expect(store.getByWorkspaceId(baseline.workspaceId)).toMatchObject({
        status: 'READY',
        branchName: 'canonical',
      });
      workspaceEvents.emit(WORKSPACE_STATE_CHANGED, {
        workspaceId: baseline.workspaceId,
        fromStatus: 'READY',
        toStatus: 'READY',
        workspace: {
          ...baseline,
          updatedAt: new Date(201),
          createdAt: new Date(baseline.createdAt),
          branchName: 'newer canonical',
        },
      });
      expect(store.getByWorkspaceId(baseline.workspaceId)?.branchName).toBe('newer canonical');
    } finally {
      collector.stop();
      store.clear();
    }
  }
);
